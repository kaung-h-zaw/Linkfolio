import { openSectionCard } from './helpers/designControls.js'
import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { getDesign } from '../src/lib/resumeDesign.js'
import { getExperience } from '../src/lib/experience.js'
import { textDocument } from '../src/lib/summary.js'
const headers = {'X-Linkfolio-Request':'1'}
test('summary, skills and date layouts preserve content, formatting and saved choices', async ({page},testInfo) => {
  const errors=[]
  page.on('pageerror',(error) => errors.push(error.message))
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Layout Owner',email:`layouts-${crypto.randomUUID()}@example.com`,password:'layout test password'}})
  const id=crypto.randomUUID()
  const content=textDocument('Design accessible products.\nBuild useful software.')
  content.content[0].content[0].marks=[{type:'bold'}]
  const experienceSection=getExperience(sampleProfile)
  experienceSection.entries[0].location='Bangkok'
  const document={...sampleProfile,id,kind:'resume',name:'Layout resume',templateId:'essential',design:getDesign({entryLayout:'columns',sectionStyles:{summary:{contentLayout:'bullets'}}}),summarySection:{heading:'Summary',entries:[{id:'intro',visible:true,content}]},experienceSection}
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:document})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await page.getByRole('button',{name:'Section customizations',exact:true}).click()
  let selectedCard;const choose=async key=>{selectedCard=await openSectionCard(page,key)}
  await expect(page.locator('[data-section-customization=summary]')).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Summary layout: Bullet points',exact:true})).toHaveCount(0)
  const summary=page.locator('#editor-preview .resume-page [data-section=summary]').first()
  await expect(summary.locator('.summary-rich-text > p')).toHaveCount(1)
  await expect(summary.locator('.summary-rich-text > p')).toHaveText('Design accessible products. Build useful software.')
  await expect(summary.locator('strong')).toHaveText('Design accessible products.')
  await expect(summary.locator('ul')).toHaveCount(0)
  await choose('skills')
  const skills=page.locator('#editor-preview .resume-page [data-section=skills]').first()
  const names=await skills.locator('.resume-skill h4').allTextContents()
  await page.getByRole('button',{name:'Skills style: Rows',exact:true}).click()
  expect((await skills.locator('.resume-skills').evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(' '))).length).toBe(1)
  await page.getByRole('button',{name:'Skills style: Grid',exact:true}).click()
  expect((await skills.locator('.resume-skills').evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(' '))).length).toBe(2)
  await page.getByRole('button',{name:'Skills style: Bubble',exact:true}).click()
  await expect(skills.locator('.resume-skills')).toHaveCSS('display','flex')
  await expect(skills.locator('.resume-skill').first()).toHaveCSS('border-top-style','solid')
  expect(await skills.locator('.resume-skill h4').allTextContents()).toEqual(names)
  await page.screenshot({path:testInfo.outputPath('skills-layout-desktop.png')})
  await page.setViewportSize({width:320,height:844})
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('skills-layout-mobile.png')})
  await page.setViewportSize({width:1440,height:1000})
  await choose('experience')
  const entry=page.locator('#editor-preview .resume-page [data-section=experience] .resume-entry').first()
  await selectedCard.getByRole('button',{name:'Section layout: Dates below',exact:true}).click()
  await expect(entry).toHaveCSS('display','block')
  await expect(entry.locator('.resume-entry-meta')).toHaveCSS('display','flex')
  await expect(entry.locator('.resume-entry-meta')).toHaveCSS('margin-top','4px')
  await expect(entry.locator('.resume-entry-location')).toHaveText('Bangkok')
  await selectedCard.getByRole('button',{name:'Section layout: Dates on the right',exact:true}).click()
  await expect(entry).toHaveCSS('display','grid')
  await expect(entry.locator('.resume-entry-meta')).toHaveCSS('text-align','right')
  await choose('certifications')
  const certificate=page.locator('#editor-preview .resume-page [data-section=certifications] .resume-entry').first()
  await selectedCard.getByRole('button',{name:'Section layout: Dates below',exact:true}).click()
  await expect(certificate).toHaveCSS('display','block')
  await expect(certificate.locator('.resume-entry-meta')).toHaveCSS('display','flex')
  await expect(certificate.locator('.resume-entry-dates')).toContainText('Issued')
  await selectedCard.getByRole('button',{name:'Section layout: Dates on the right',exact:true}).click()
  await expect(certificate).toHaveCSS('display','grid')
  await expect(certificate.locator('.resume-entry-meta')).toHaveCSS('text-align','right')
  await expect(certificate.locator('h4')).toHaveText('Accessible Digital Design')
  await expect(certificate.locator('.resume-entry-titles')).toContainText('Design Learning Academy')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(summary.locator('.summary-rich-text > p')).toHaveCount(1)
  await expect(summary.locator('ul')).toHaveCount(0)
  await expect(skills).toHaveAttribute('data-content-layout','tags')
  await expect(entry).toHaveCSS('display','grid')
  await expect(certificate).toHaveCSS('display','grid')
  const saved=(await (await page.request.get('/api/documents')).json()).documents.find((item) => item.id===id)
  expect(saved.summarySection.entries[0].content).toEqual(content)
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download resume',exact:true}).click()
  const download=await downloadEvent
  await download.saveAs(testInfo.outputPath('section-layouts.pdf'))
  expect(await download.failure()).toBeNull()
  expect(errors).toEqual([])
})
