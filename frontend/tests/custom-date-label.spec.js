import {test,expect} from './fixtures.js'
import {sampleProfile} from '../src/components/resumeTemplates.js'
import {newContentEntry} from '../src/lib/contentCatalog.js'
const headers={'X-Linkfolio-Request':'1'}
test('custom single dates support preset, blank and custom labels without changing date ranges',async({page},testInfo)=>{
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Date labels',email:`dates-${crypto.randomUUID()}@example.com`,password:'custom date password'}})
  const id=crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:{...sampleProfile,id,kind:'resume',name:'Date labels',templateId:'essential',extraContent:[{type:'custom',heading:'Awards',entries:[{...newContentEntry(),name:'Community award',startDate:'2025-11'}]}]}})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('button',{name:'Awards',exact:true}).click()
  await page.getByRole('button',{name:'Edit custom entry 1',exact:true}).click()
  const preview=page.locator('#editor-preview .resume-page [data-section=custom]').first()
  const label=page.getByLabel('Date label',{exact:true})
  await expect(label).toHaveValue('')
  await label.selectOption('Issued')
  await expect(preview).toContainText('Issued Nov 2025')
  await label.selectOption('')
  await expect(preview).not.toContainText('Issued')
  await expect(preview).toContainText('Nov 2025')
  await label.selectOption('custom')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Enter a date label.')
  await page.getByLabel('Custom date label',{exact:true}).fill('Received')
  await expect(preview).toContainText('Received Nov 2025')
  await page.getByLabel('End date',{exact:true}).fill('2026-01')
  await expect(label).toHaveCount(0)
  await expect(preview).toContainText('Nov 2025 — Jan 2026')
  await expect(preview).not.toContainText('Received')
  await page.getByLabel('End date',{exact:true}).fill('')
  await page.getByLabel('Ongoing',{exact:true}).check()
  await expect(label).toHaveCount(0)
  await expect(preview).toContainText('Nov 2025 — Present')
  await page.getByLabel('Ongoing',{exact:true}).uncheck()
  await expect(label).toHaveValue('custom')
  await page.setViewportSize({width:320,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('single-date-label-mobile.png')})
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.setViewportSize({width:1440,height:1000})
  await page.reload()
  await expect(preview).toContainText('Received Nov 2025')
  const saved=(await(await page.request.get('/api/documents')).json()).documents.find(item=>item.id===id)
  expect(saved.extraContent[0].entries[0]).toMatchObject({dateLabel:'custom',customDateLabel:'Received',startDate:'2025-11',endDate:'',current:false})
})
