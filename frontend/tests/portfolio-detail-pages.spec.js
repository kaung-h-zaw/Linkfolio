import {test,expect} from './fixtures.js'
import {fileURLToPath} from 'node:url'
import {sampleProfile} from '../src/components/resumeTemplates.js'
import {defaultPortfolio} from '../src/lib/portfolio.js'
import {getProjects} from '../src/lib/additionalSections.js'
import {textDocument} from '../src/lib/summary.js'
const headers={'X-Linkfolio-Request':'1'}
test.use({actionTimeout:15000})
test('portfolio detail pages, custom destinations, galleries and global section order preserve privacy',async({page},testInfo)=>{
  const errors=[]
  page.on('pageerror',(error)=>errors.push(error.message))
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Detail Owner',email:`detail-${crypto.randomUUID()}@example.com`,password:'detail test password'}})
  await page.goto('/premium')
  await page.getByRole('button',{name:'Try demo upgrade',exact:true}).click()
  await page.getByRole('button',{name:'Simulate successful payment',exact:true}).click()
  await page.getByText('Demo payment successful. Premium is active.',{exact:true}).waitFor()
  const sourceId=crypto.randomUUID(),id=crypto.randomUUID()
  const projects=getProjects(sampleProfile)
  projects.entries[0].content=textDocument('Project overview and implementation. '.repeat(25)+'Full project detail end.')
  projects.entries.push({...projects.entries[0],id:'hidden-project',name:'PRIVATE PROJECT CANARY',visible:false})
  const custom={type:'custom',heading:'Volunteering',format:'standard',showInResume:false,showInPortfolio:true,entries:[{id:'mentoring',name:'Community mentoring',subtitle:'Coding programme',visible:true,content:textDocument('Mentoring and accessibility workshops. '.repeat(20)+'Full mentoring detail end.'),url:'https://example.com/mentoring'},{id:'private-custom',name:'PRIVATE CUSTOM CANARY',visible:false,content:textDocument('PRIVATE DESCRIPTION CANARY')}]}
  const source={...sampleProfile,id:sourceId,kind:'resume',name:'Detail source',templateId:'essential',projectsSection:projects,extraContent:[custom]}
  const portfolio={...source,id,kind:'portfolio',name:'Detail portfolio',portfolio:{...defaultPortfolio,template:'bento',resumeDownload:true,sourceResume:{id:sourceId,name:source.name},images:{projects:{[projects.entries[0].id]:'/images/portfolio-workspace.jpg'}},detailPages:{'projects:hidden-project':{enabled:true,images:['/images/portfolio-desk.jpg']},'custom:private-custom':{enabled:true,images:['/images/portfolio-desk.jpg']}}}}
  for(const document of [source,portfolio]) expect((await page.request.put(`/api/documents/${document.id}`,{headers,data:document})).status()).toBe(200)
  await page.goto(`/editor?resume=${sourceId}`)
  await expect(page.locator('#editor-preview .resume-page [data-section=custom]')).toHaveCount(0)
  await page.getByRole('button',{name:'Volunteering',exact:true}).click()
  await page.getByRole('button',{name:'Edit custom entry 1',exact:true}).click()
  await page.getByText('Section settings',{exact:true}).click()
  await expect(page.getByLabel('Show in resume',{exact:true})).not.toBeChecked()
  await expect(page.getByLabel('Show in portfolio',{exact:true})).toBeChecked()
  await page.getByLabel('Show in resume',{exact:true}).check()
  await expect(page.locator('#editor-preview .resume-page [data-section=custom]')).toContainText('Community mentoring')
  await page.getByLabel('Show in resume',{exact:true}).uncheck()
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.goto(`/portfolio/editor?resume=${id}`)
  const projectName=projects.entries[0].name
  await page.getByRole('button',{name:`Add details for ${projectName}`,exact:true}).click()
  await page.getByRole('dialog',{name:'Add detail page',exact:true}).getByRole('button',{name:'Cancel',exact:true}).click()
  await expect(page.locator('#editor-preview [data-section=projects]').getByRole('button',{name:'View details',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:`Add details for ${projectName}`,exact:true}).click()
  await page.getByRole('dialog',{name:'Add detail page',exact:true}).getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('button',{name:'Add details for Community mentoring',exact:true}).click()
  const detailForm=page.getByRole('dialog',{name:'Add detail page',exact:true})
  await page.screenshot({path:testInfo.outputPath('detail-form-desktop.png')})
  await expect(page.getByRole('button',{name:'Add details for PRIVATE PROJECT CANARY',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Add details for PRIVATE CUSTOM CANARY',exact:true})).toHaveCount(0)
  const customDescription='I designed a mentoring programme, created accessible learning materials, and coached new developers.\n\nThe programme helped twenty learners build and share their first project. Full mentoring detail end.'
  await detailForm.getByLabel('Description',{exact:true}).fill(customDescription)
  await detailForm.getByText('Links (optional)',{exact:true}).click()
  await detailForm.getByLabel('Website',{exact:true}).fill('javascript:alert(1)')
  await detailForm.getByRole('button',{name:'Done',exact:true}).click()
  await expect(detailForm.getByRole('alert')).toContainText('valid web address')
  await detailForm.getByLabel('Website',{exact:true}).fill('https://example.com/detail-mentoring')
  await page.setViewportSize({width:320,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('detail-form-mobile.png')})
  await page.setViewportSize({width:1440,height:1000})
  await detailForm.getByRole('button',{name:'Add detail image: community mentoring',exact:true}).click()
  await page.getByLabel('Choose detail image: community mentoring',{exact:true}).setInputFiles(fileURLToPath(new URL('../public/images/portfolio-desk.jpg',import.meta.url)))
  await page.getByRole('button',{name:'Use image',exact:true}).click()
  await detailForm.getByRole('button',{name:'Done',exact:true}).click()
  await page.locator('#editor-preview [data-section=custom]').getByRole('button',{name:'View details',exact:true}).click()
  await expect(page.locator('#editor-preview h1')).toHaveText('Community mentoring')
  await expect(page.locator('#editor-preview')).toContainText('Full mentoring detail end.')
  await expect(page.locator('#editor-preview .portfolio-detail-gallery img')).toHaveCount(1)
  await page.locator('#editor-preview').getByRole('button',{name:'Back to portfolio',exact:true}).click()
  const arrange=page.getByRole('region',{name:'Arrange portfolio sections',exact:true})
  await arrange.evaluate((element)=>element.scrollIntoView({block:'start',behavior:'instant'}))
  await expect(arrange.getByRole('button',{name:/Move .* (up|down)/})).toHaveCount(0)
  const handle=arrange.getByRole('button',{name:'Drag Volunteering to reorder',exact:true})
  const from=await handle.boundingBox(),to=await arrange.locator('[data-order-section=projects]').boundingBox()
  await page.mouse.move(from.x+from.width/2,from.y+from.height/2)
  await page.mouse.down()
  await page.mouse.move(to.x+to.width/2,to.y+8,{steps:15})
  await expect(arrange.locator('[data-order-section]').first()).toHaveAttribute('data-order-section','custom')
  await expect(page.locator('.section-drag-floating')).toBeVisible()
  await page.mouse.up()
  await expect(page.locator('.section-drag-floating')).toHaveCount(0)
  await handle.focus()
  await handle.press('ArrowDown')
  await expect(arrange.locator('[data-order-section]').first()).not.toHaveAttribute('data-order-section','custom')
  await handle.press('ArrowUp')
  await expect(arrange.locator('[data-order-section]').first()).toHaveAttribute('data-order-section','custom')
  await arrange.getByLabel('Show Volunteering section',{exact:true}).uncheck()
  await expect(page.locator('#editor-preview [data-section=custom]')).toHaveCount(0)
  await arrange.getByLabel('Show Volunteering section',{exact:true}).check()
  await page.setViewportSize({width:320,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await arrange.scrollIntoViewIfNeeded()
  await page.screenshot({path:testInfo.outputPath('portfolio-content-order-mobile.png')})
  await page.setViewportSize({width:1440,height:1000})
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await page.getByRole('button',{name:'Section customizations',exact:true}).click()
  await expect(page.getByRole('button',{name:'Move projects up',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'General',exact:true}).click()
  await page.getByText('Choose portfolio template',{exact:true}).click()
  await page.getByRole('button',{name:'Use Signal template',exact:true}).click()
  await expect(page.locator('#editor-preview .portfolio-section').first()).toHaveAttribute('data-section','custom')
  await page.getByRole('button',{name:'Reset design to template defaults',exact:true}).click()
  await expect(page.locator('#editor-preview .portfolio-section').first()).toHaveAttribute('data-section','custom')
  await page.getByRole('button',{name:'Content',exact:true}).click()
  await expect(arrange.locator('[data-order-section]').first()).toHaveAttribute('data-order-section','custom')
  await page.screenshot({path:testInfo.outputPath('portfolio-content-order.png')})
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  const documents=(await(await page.request.get('/api/documents')).json()).documents
  const saved=documents.find((item)=>item.id===id),slug=saved.publication.slug
  expect((await page.request.put(`/api/documents/${id}/publication`,{headers,data:{slug,visibility:'public'}})).status()).toBe(200)
  const published=await(await page.request.get(`/api/public/portfolios/${slug}`)).json()
  expect(JSON.stringify(published)).not.toContain('PRIVATE PROJECT CANARY')
  expect(JSON.stringify(published)).not.toContain('PRIVATE CUSTOM CANARY')
  expect(published.settings.detailPages['custom:mentoring'].description).toBe(customDescription)
  expect(published.profile.extraContent[0].entries[0].content).toEqual(custom.entries[0].content)
  expect(published.settings.detailPages['projects:hidden-project']).toBeUndefined()
  expect(published.settings.detailPages['custom:private-custom']).toBeUndefined()
  expect(published.resumeProfile.extraContent).toEqual([])
  const visitor=await page.context().newPage()
  await visitor.goto(`/p/${slug}`)
  await expect(visitor.locator('.portfolio-section').first()).toHaveAttribute('data-section','custom')
  await expect(visitor.locator('[data-section=custom]')).not.toContainText('Full mentoring detail end.')
  await visitor.locator('[data-section=custom]').getByRole('link',{name:'View details',exact:true}).click()
  await expect(visitor).toHaveURL(new RegExp(`/p/${slug}/custom/mentoring$`))
  await expect(visitor.getByRole('heading',{level:1})).toHaveText('Community mentoring')
  await expect(visitor.locator('.portfolio-detail-description')).toContainText('The programme helped twenty learners')
  await expect(visitor.getByRole('link',{name:'Open link',exact:true})).toHaveAttribute('href','https://example.com/detail-mentoring')
  await expect(visitor.locator('.portfolio-detail-gallery img')).toHaveCount(1)
  await visitor.screenshot({path:testInfo.outputPath('custom-detail-desktop.png'),fullPage:true})
  await visitor.setViewportSize({width:320,height:844})
  expect(await visitor.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await visitor.screenshot({path:testInfo.outputPath('custom-detail-mobile.png'),fullPage:true})
  await visitor.reload()
  await expect(visitor.getByRole('heading',{level:1})).toHaveText('Community mentoring')
  await visitor.getByRole('link',{name:'Back to portfolio',exact:true}).click()
  await visitor.locator('[data-section=projects]').getByRole('link',{name:'View details',exact:true}).click()
  await expect(visitor.locator('.portfolio-detail-description')).toContainText('Full project detail end.')
  await expect(visitor.locator('.portfolio-detail-gallery img')).toHaveCount(1)
  await visitor.goto(`/p/${slug}/custom/private-custom`)
  await expect(visitor.getByRole('heading',{name:'Detail page unavailable',exact:true})).toBeVisible()
  // Withdraw custom content: deep links and gallery data must disappear too.
  const currentSource=documents.find((item)=>item.id===sourceId)
  currentSource.extraContent[0].showInPortfolio=false
  expect((await page.request.put(`/api/documents/${sourceId}`,{headers,data:currentSource})).status()).toBe(200)
  await visitor.goto(`/p/${slug}/custom/mentoring`)
  await expect(visitor.getByRole('heading',{name:'Detail page unavailable',exact:true})).toBeVisible()
  const withdrawn=await(await page.request.get(`/api/public/portfolios/${slug}`)).json()
  expect(withdrawn.profile.extraContent).toEqual([])
  expect(withdrawn.settings.detailPages['custom:mentoring']).toBeUndefined()
  expect((await page.request.put(`/api/documents/${id}/publication`,{headers,data:{slug,visibility:'private'}})).status()).toBe(200)
  await visitor.goto(`/p/${slug}/projects/${projects.entries[0].id}`)
  await expect(visitor.getByRole('heading',{name:'Portfolio unavailable',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})
