import {test,expect} from './fixtures.js'
import {sampleProfile} from '../src/components/resumeTemplates.js'
import {newContentEntry} from '../src/lib/contentCatalog.js'
const headers={'X-Linkfolio-Request':'1'}
test('custom standard fields, validation and skill groups preserve data across type changes and reloads',async({page},testInfo)=>{
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Custom Types',email:`types-${crypto.randomUUID()}@example.com`,password:'custom types password'}})
  const id=crypto.randomUUID()
  const custom={type:'custom',heading:'Volunteering',entries:[newContentEntry()]}
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:{...sampleProfile,id,kind:'resume',name:'Custom types',templateId:'essential',extraContent:[custom]}})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('button',{name:'Volunteering',exact:true}).click()
  await page.getByRole('button',{name:'Edit custom entry 1',exact:true}).click()
  await page.getByLabel('Title',{exact:true}).fill('Volunteer mentor')
  await page.getByLabel('Subtitle',{exact:true}).fill('Community coding programme')
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('Mentored new developers in accessible web development.')
  await expect(page.getByLabel('Start date',{exact:true})).toBeHidden()
  await page.getByText('Dates, location & link (optional)',{exact:true}).click()
  await page.getByLabel('Start date',{exact:true}).fill('2025-01')
  await page.getByLabel('End date',{exact:true}).fill('2024-12')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('End date must be on or after start date.')
  await page.getByLabel('End date',{exact:true}).fill('2025-12')
  await page.getByLabel('Location',{exact:true}).fill('Bangkok, Thailand')
  await page.getByLabel('Title link',{exact:true}).fill('javascript:alert(1)')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('Enter a valid web address.')
  await page.getByLabel('Title link',{exact:true}).fill('https://example.com/mentoring')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  const preview=page.locator('#editor-preview .resume-page [data-section=custom]').first()
  await expect(preview.getByRole('link',{name:'Volunteer mentor',exact:true})).toHaveAttribute('href','https://example.com/mentoring')
  await expect(preview).toContainText('Community coding programme')
  await expect(preview).toContainText('Bangkok, Thailand')
  await page.screenshot({path:testInfo.outputPath('standard-custom-entry.png')})
  await page.getByRole('button',{name:'Edit custom entry 1',exact:true}).click()
  await page.getByText('Section settings',{exact:true}).click()
  await page.getByRole('button',{name:'Custom section type: Skill groups',exact:true}).click()
  await expect(preview).not.toContainText('Bangkok, Thailand')
  await expect(preview.locator('.resume-entry-header')).toHaveCount(0)
  await expect(preview).toContainText('Volunteer mentor')
  await expect(preview).toContainText('Mentored new developers')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await page.getByRole('button',{name:'Volunteering',exact:true}).click()
  await page.getByRole('button',{name:'Edit custom entry 1',exact:true}).click()
  await page.getByText('Section settings',{exact:true}).click()
  await expect(page.getByRole('button',{name:'Custom section type: Skill groups',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(page.getByLabel('Group heading',{exact:true})).toHaveValue('Volunteer mentor')
  await expect(page.getByRole('textbox',{name:'Details',exact:true})).toContainText('Mentored new developers')
  await page.getByRole('button',{name:'Custom section type: Standard entries',exact:true}).click()
  await expect(page.getByLabel('Subtitle',{exact:true})).toHaveValue('Community coding programme')
  await expect(page.getByLabel('Start date',{exact:true})).toHaveValue('2025-01')
  await expect(page.getByLabel('End date',{exact:true})).toHaveValue('2025-12')
  await expect(page.getByLabel('Title link',{exact:true})).toHaveValue('https://example.com/mentoring')
  await page.setViewportSize({width:320,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('custom-type-mobile.png')})
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  const document=(await(await page.request.get('/api/documents')).json()).documents.find(item=>item.id===id)
  expect(document.extraContent[0]).toMatchObject({format:'standard',entries:[{name:'Volunteer mentor',subtitle:'Community coding programme',location:'Bangkok, Thailand',startDate:'2025-01',endDate:'2025-12',url:'https://example.com/mentoring'}]})
})
