test('APP-THEME-01 system, light, and dark preferences persist across reloads', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/register')
  await page.getByLabel('Full Name').fill('Theme Test User')
  await page.getByLabel('Email').fill(`theme-${Date.now()}@example.test`)
  await page.getByLabel('Password', { exact: true }).fill('ChapterSixPass123!')
  await page.getByLabel('Confirm Password', { exact: true }).fill('ChapterSixPass123!')
  await page.getByRole('button', { name: /create account/i }).click()
  await expect(page).toHaveURL(/\/setup/)
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'dark')
  const selectedNav = page.locator('.app-sidebar nav a[aria-current="page"]')
  await expect.poll(() => selectedNav.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(41, 45, 48)')
  await expect.poll(() => selectedNav.locator('svg').evaluate(element => getComputedStyle(element).color)).toBe('rgb(52, 211, 153)')
  await expect.poll(() => page.getByRole('button', { name: 'Create resume' }).evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(5, 150, 105)')
  await page.getByRole('link', { name: 'Account', exact: true }).click()
  const appearance = page.getByRole('group', { name: 'App appearance' })
  await appearance.getByRole('button', { name: 'Dark' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'dark')
  const selectedAppearance = appearance.getByRole('button', { name: 'Dark' })
  await expect.poll(() => selectedAppearance.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(41, 45, 48)')
  await expect.poll(() => selectedAppearance.evaluate(element => getComputedStyle(element).borderColor)).toBe('rgb(69, 75, 80)')
  await expect.poll(() => selectedAppearance.locator('svg').evaluate(element => getComputedStyle(element).color)).toBe('rgb(52, 211, 153)')
  await expect.poll(() => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--app-canvas').trim())).toBe('#111315')
  await expect.poll(() => page.evaluate(() => getComputedStyle(document.documentElement).getPropertyValue('--app-accent').trim())).toBe('#059669')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'dark')
  await expect(page.evaluate(() => localStorage.getItem('linkfolio.appearance'))).resolves.toBe('dark')
  await appearance.getByRole('button', { name: 'Light' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'light')
  const lightAppearance = appearance.getByRole('button', { name: 'Light' })
  await expect.poll(() => lightAppearance.evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(244, 244, 245)')
  await expect.poll(() => lightAppearance.evaluate(element => getComputedStyle(element).borderColor)).toBe('rgb(212, 212, 216)')
  await expect.poll(() => lightAppearance.locator('svg').evaluate(element => getComputedStyle(element).color)).toBe('rgb(4, 120, 87)')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'light')
  await appearance.getByRole('button', { name: 'System' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'dark')
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'dark')
  await expect(page.evaluate(() => localStorage.getItem('linkfolio.appearance'))).resolves.toBe('system')
})

test('RES-PDF-01 export a resume from the editor as a PDF download', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/register')
  await page.getByLabel('Full Name').fill('PDF Evidence User')
  await page.getByLabel('Email').fill(`pdf-evidence-${Date.now()}@example.test`)
  await page.getByLabel('Password', { exact: true }).fill('ChapterSixPass123!')
  await page.getByLabel('Confirm Password', { exact: true }).fill('ChapterSixPass123!')
  await page.getByRole('button', { name: /create account/i }).click()
  await expect(page).toHaveURL(/\/setup/)
  await page.getByRole('button', { name: 'Create resume' }).click()
  await page.getByRole('button', { name: 'Create a new resume' }).click()
  await expect(page.getByRole('heading', { name: 'Choose a resume template' })).toBeVisible()
  await page.getByRole('button', { name: /Preview .* template/ }).first().click()
  await page.getByRole('button', { name: 'Use this template' }).click()
  await expect(page).toHaveURL(/\/editor/)
  await expect(page.locator('html')).toHaveAttribute('data-app-theme', 'dark')
  await expect.poll(() => page.locator('.resume-document').first().evaluate(element => getComputedStyle(element).backgroundColor)).toBe('rgb(255, 255, 255)')
  await expect(page.getByRole('button', { name: 'Download resume' })).toBeVisible()
  await page.screenshot({ path: 'test-results/artifacts/resume-editor-before-export.png', fullPage: true })
  const downloadPromise = page.waitForEvent('download', { timeout: 60_000 })
  await page.getByRole('button', { name: 'Download resume' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.pdf$/i)
  await download.saveAs('test-results/artifacts/resume-export.pdf')
})
