import {test,expect} from '@playwright/test'
import {sampleProfile} from '../src/components/resumeTemplates.js'
import {getDesign} from '../src/lib/resumeDesign.js'
import {textDocument} from '../src/lib/summary.js'
import {openSectionCard} from './helpers/designControls.js'
const headers={'X-Linkfolio-Request':'1'}
test('custom skill groups share collection styles and removed level styles fall back to Grid',async({page},testInfo)=>{
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Skill groups',email:`group-${crypto.randomUUID()}@example.com`,password:'custom skill password'}})
  const id=crypto.randomUUID(),key=`custom_${crypto.randomUUID()}`,title='Technical skill groups'
  const entries=[['Frontend','React, accessible interfaces'],['Backend','Node.js, REST APIs'],['Workflow','Git, Figma']].map(([name,text])=>({id:crypto.randomUUID(),name,visible:true,content:textDocument(text)}))
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:{...sampleProfile,id,kind:'resume',name:'Custom skill groups',templateId:'essential',design:{...getDesign(),sectionStyles:{languages:{contentLayout:'level',levelDisplay:'bar'},skills:{contentLayout:'level'}}},extraContent:[{type:key,heading:title,format:'skills',entries}]}})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await expect(page.locator('#editor-preview .resume-level-indicator')).toHaveCount(0)
  await page.getByRole('button',{name:'Design',exact:true}).click()
  const card=await openSectionCard(page,key)
  await expect(card.getByText('Content layout',{exact:true})).toHaveCount(0)
  await expect(card.getByText('Entry layout',{exact:true})).toHaveCount(0)
  for(const name of ['Skills','Languages','Certifications',title])await expect(page.getByRole('button',{name:`${name} style: Level`,exact:true})).toHaveCount(0)
  const content=page.locator(`#editor-preview .resume-page [data-section="${key}"] .resume-section-collection`).first()
  await card.getByRole('button',{name:`${title} style: Grid`,exact:true}).click()
  await card.getByRole('button',{name:`${title} columns: 3`,exact:true}).click()
  expect((await content.evaluate(el=>getComputedStyle(el).gridTemplateColumns.split(' '))).length).toBe(3)
  await card.getByRole('button',{name:`${title} style: Rows`,exact:true}).click()
  await card.getByRole('button',{name:`${title} Row spacing: Spacious`,exact:true}).click()
  await card.getByRole('checkbox',{name:'Start rows with bullets',exact:true}).check()
  await card.getByRole('button',{name:`${title} Subinfo style: : Colon`,exact:true}).click()
  await expect(content).toHaveCSS('row-gap','14px')
  await expect(content.locator('.resume-collection-subinfo').first()).toHaveCSS('display','inline')
  await card.getByRole('button',{name:`${title} style: Compact`,exact:true}).click()
  await card.getByRole('button',{name:`${title} Separator: Pipe`,exact:true}).click()
  await expect(content).toHaveCSS('display','block')
  await card.getByRole('button',{name:`${title} style: Bubble`,exact:true}).click()
  await expect(content).toHaveCSS('display','flex')
  await expect(content.locator(':scope > div').first()).toHaveCSS('border-top-style','solid')
  await content.screenshot({path:testInfo.outputPath('custom-groups-bubble.png')})
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(content).toHaveAttribute('data-collection-layout','tags')
  await expect(content).toContainText('REST APIs')
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await openSectionCard(page,key)
  await page.setViewportSize({width:320,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await card.screenshot({path:testInfo.outputPath('custom-groups-mobile.png')})
  const event=page.waitForEvent('download');await page.getByRole('button',{name:'Download resume',exact:true}).click();expect(await(await event).failure()).toBeNull()
})
