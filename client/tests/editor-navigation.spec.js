test('both editors expose clear button navigation and working back destinations on every screen size', async ({ page },testInfo) => {
  const errors=[]
  page.on('pageerror',(error) => errors.push(error.message))
  expect((await page.request.post('/api/auth/register',{ headers,data:{ fullName:'Alex Morgan',email:`navigation-${crypto.randomUUID()}@example.com`,password:'navigation password' } })).status()).toBe(201)
  const id=crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`,{ headers,data:{ ...sampleProfile,id,name:'Navigation study',kind:'resume',templateId:'essential',portfolio:defaultPortfolio } })).status()).toBe(200)
  for (const portfolio of [false,true]) {
    await page.goto(`${portfolio ? '/portfolio/editor' : '/editor'}?resume=${id}`)
    if (portfolio) await expect(page.getByLabel('Portfolio URL',{ exact:true })).toHaveCount(0)
    const toolbar=page.locator('.editor-navigation-bar')
    const nav=page.getByRole('navigation',{ name:'Editor navigation',exact:true })
    const back=toolbar.getByRole('link',{ name:'Home',exact:true })
    await expect(back).toHaveAttribute('href',portfolio?'/dashboard':'/setup')
    for (const width of [1440,768,390,320]) {
      await page.setViewportSize({ width,height:1000 })
      await expect(back).toBeVisible()
      expect(await page.evaluate(() => document.documentElement.scrollWidth<=innerWidth)).toBe(true)
      for (const name of ['Content','Design']) {
        const button=nav.getByRole('button',{ name,exact:true })
        await expect(button).toBeVisible()
        expect((await button.boundingBox()).height).toBeGreaterThanOrEqual(44)
      }
      const homeBox = await back.boundingBox()
      const contentButton = nav.getByRole('button', { name:'Content',exact:true })
      const contentBox = await contentButton.boundingBox()
      expect(homeBox.height).toBe(contentBox.height)
      if (width >= 768) expect(homeBox.width).toBe(contentBox.width)
      expect(await back.locator('span').evaluate((element) => getComputedStyle(element).fontSize)).toBe(await contentButton.locator('span').evaluate((element) => getComputedStyle(element).fontSize))
      await page.screenshot({ path:testInfo.outputPath(`${portfolio ? 'portfolio' : 'resume'}-navigation-${width}.png`) })
    }
    await nav.getByRole('button',{ name:'Design',exact:true }).click()
    await expect(nav.getByRole('button',{ name:'Design',exact:true })).toHaveAttribute('aria-current','page')
    if (portfolio) {
      await nav.getByRole('button',{ name:'Sharing',exact:true }).click()
      await expect(page.getByLabel('Portfolio URL',{ exact:true })).toBeVisible()
      await expect(page.locator('#portfolio-publication')).toBeFocused()
      await expect(page).toHaveURL(/\/portfolio\/editor\/share\?/)
      await page.getByLabel('Visibility',{ exact:true }).selectOption('public')
      await page.getByRole('button',{ name:'Publish portfolio',exact:true }).click()
      await expect(page.getByText('Your portfolio is published.',{ exact:true })).toBeVisible()
      await nav.getByRole('button',{ name:'Content',exact:true }).click()
      await expect(page.getByLabel('Portfolio URL',{ exact:true })).toHaveCount(0)
      await expect(page.getByRole('heading',{ name:'Portfolio content',exact:true })).toBeVisible()
      await nav.getByRole('button',{ name:'Sharing',exact:true }).click()
      await expect(page.getByLabel('Visibility',{ exact:true })).toHaveValue('public')
    } else {
      await nav.getByRole('button',{ name:'Content',exact:true }).click()
      await page.getByRole('button',{ name:'Edit personal details',exact:true }).click()
      await page.getByRole('button',{ name:'Done',exact:true }).click()
      await expect(page.getByRole('button',{ name:'Edit personal details',exact:true })).toBeVisible()
    }
    await toolbar.getByRole('button',{ name:'Save',exact:true }).click()
    await expect(toolbar.getByRole('status')).toContainText('Saved to your account')
    await toolbar.getByRole('button',{ name:'Preview',exact:true }).click()
    await expect(toolbar).toBeHidden()
    await page.getByRole('button',{ name:'Close preview',exact:true }).click()
    await expect(toolbar.getByRole('button',{ name:'Preview',exact:true })).toBeFocused()
    await back.click()
    await expect(page.getByRole('heading',{ name:portfolio?'Your dashboard':'My resumes',exact:true,level:1 })).toBeVisible()
  }
  expect(errors).toEqual([])
})

test('editor columns scroll independently without visible tracks while navigation stays reachable', async ({ page }, testInfo) => {
  expect((await page.request.post('/api/auth/register', { headers, data: { fullName:'Alex Morgan', email:`scroll-${crypto.randomUUID()}@example.com`, password:'scrolling password' } })).status()).toBe(201)
  const id = crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`, { headers, data: { ...sampleProfile, id, name:'Scrolling study', kind:'resume', templateId:'essential', portfolio:defaultPortfolio } })).status()).toBe(200)
  for (const portfolio of [false, true]) {
    for (const [width, height] of [[1440,600], [768,600], [390,600], [320,500]]) {
      await page.setViewportSize({ width, height })
      await page.goto(`${portfolio ? '/portfolio/editor' : '/editor'}?resume=${id}`)
      const nav = page.getByRole('navigation', { name:'Editor navigation', exact:true })
      await nav.getByRole('button', { name:'Design', exact:true }).click()
      if (width >= 768) {
        const left = page.locator('#editor-content')
        const right = page.locator('.editor-preview-canvas')
        const previewBox = await right.boundingBox()
        await page.mouse.move(previewBox.x + 80, previewBox.y + 100)
        await page.mouse.wheel(0, 260)
        await expect.poll(() => right.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
        expect(await left.evaluate((element) => element.scrollTop)).toBe(0)
        const rightScroll = await right.evaluate((element) => element.scrollTop)
        const editorBox = await left.boundingBox()
        await page.mouse.move(editorBox.x + 80, editorBox.y + 100)
        await page.mouse.wheel(0, 260)
        await expect.poll(() => left.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
        expect(await right.evaluate((element) => element.scrollTop)).toBe(rightScroll)
        expect(await page.evaluate(() => window.scrollY)).toBe(0)
        for (const pane of [left, right]) {
          expect(await pane.evaluate((element) => getComputedStyle(element).scrollbarWidth)).toBe('none')
        }
      }
      const reset = page.getByRole('button', { name:portfolio ? 'Reset design to template defaults' : 'Reset design settings', exact:true })
      await reset.scrollIntoViewIfNeeded()
      await expect(reset).toBeInViewport()
      expect(await page.evaluate(() => window.scrollY)).toBe(0)
      expect(await page.locator('#editor-content').evaluate((element) => element.scrollTop)).toBeGreaterThan(100)
      const bounds = await nav.boundingBox()
      const toolbar = await page.locator('.editor-navigation-bar').boundingBox()
      expect(bounds.y).toBeGreaterThanOrEqual(toolbar.y)
      expect(bounds.y + bounds.height).toBeLessThanOrEqual(toolbar.y + toolbar.height)
      expect(toolbar.height).toBeLessThanOrEqual(height * 0.3)
      expect(bounds.height).toBeLessThanOrEqual(48)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
      await page.screenshot({ path:testInfo.outputPath(`${portfolio ? 'portfolio' : 'resume'}-scroll-${width}x${height}.png`) })
      await nav.getByRole('button', { name:'Content', exact:true }).click()
      const firstContent = page.locator(portfolio ? '.editor-panel-body > section' : '.editor-panel-body > div:not(.sr-only):not([hidden])').first()
      await expect(firstContent).toBeInViewport()
      if (width >= 768) {
        const content = await firstContent.boundingBox()
        const previewStart = (await page.locator('#editor-preview').boundingBox()).y
        expect(Math.abs(content.y - previewStart)).toBeLessThanOrEqual(2)
        await page.screenshot({ path:testInfo.outputPath(`${portfolio ? 'portfolio' : 'resume'}-content-start-${width}.png`) })
      }
    }
  }
})

