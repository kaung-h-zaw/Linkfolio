import { openGeneralGroup, openSectionCard } from './helpers/designControls.js'
import { setControlValue } from './helpers/designControls.js'
import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { getDesign } from '../src/lib/resumeDesign.js'
import { defaultPortfolio } from '../src/lib/portfolio.js'

const headers = { 'X-Linkfolio-Request': '1' }
async function createDocument(page, kind) {
  expect((await page.request.post('/api/auth/register', { headers, data: { fullName: 'Alex Morgan', email: `customize-${crypto.randomUUID()}@example.com`, password: 'customization password' } })).status()).toBe(201)
  const id = crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`, { headers, data: { ...sampleProfile, id, kind, ...(kind === 'resume' ? {design:getDesign({sectionStyles:{experience:{headingSize:20,fontSize:12,spacing:36,accent:'#ff0000'}}})} : {}), name: 'Customization study', templateId: 'essential', portfolio: { ...defaultPortfolio, template: 'essential', ...(kind === 'portfolio' ? {design:{sectionStyles:{projects:{headingSize:22,fontSize:12,spacing:80,accent:'#ff0000'},hero:{headingSize:88}}}} : {}) } } })).status()).toBe(200)
  await page.goto(kind === 'resume' ? `/editor?resume=${id}` : `/portfolio/editor/design?resume=${id}`)
  if (kind === 'resume') await page.getByRole('button', { name: 'Design', exact: true }).click()
  return id
}
async function save(page) {
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Saved to your account', { exact: true }).first()).toBeVisible()
}

test('all resume section cards retain layout changes and use General appearance', async ({page})=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await createDocument(page,'resume')
  const card=await openSectionCard(page,'experience')
  await expect(page.getByLabel('Show on resume',{exact:true})).toHaveCount(0)
  await expect(page.getByLabel('Section heading',{exact:true})).toHaveCount(0)
  await expect(page.locator('[data-section-choice]')).toHaveCount(0)
  await card.getByRole('button',{name:'Section layout: Dates below',exact:true}).click()
  const experience=page.locator('#editor-preview .resume-page [data-section=experience]').first(),education=page.locator('#editor-preview .resume-page [data-section=education]').first()
  await expect(experience.locator('.resume-entry').first()).toHaveCSS('display','block')
  await openGeneralGroup(page,'Text sizes')
  await setControlValue(page.getByRole('slider',{name:'Section headings',exact:true}),'16')
  await openGeneralGroup(page,'Spacing')
  await setControlValue(page.getByRole('slider',{name:'Space between sections',exact:true}),'28')
  for(const section of [experience,education])await expect(section.locator('h3')).toHaveCSS('font-size','16px')
  await openSectionCard(page,'experience')
  await card.getByRole('button',{name:'Section layout: Dates on the right',exact:true}).click()
  await expect(experience.locator('.resume-entry').first()).toHaveCSS('display','grid')
  await save(page);await page.reload()
  await expect(experience.locator('.resume-entry').first()).toHaveCSS('display','grid')
  await expect(experience.locator('h3')).toHaveCSS('font-size','16px')
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await education.locator('h3').click()
  await expect(page.locator('[data-section-customization=education]')).toHaveAttribute('data-selected','true')
  await expect(page.getByRole('button',{name:'Section customizations',exact:true})).toHaveAttribute('aria-expanded','true')
  expect(errors).toEqual([])
})

test('portfolio sections use General appearance and keep layout and image controls', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const id = await createDocument(page, 'portfolio')
  await expect(page.getByRole('group',{name:'Section to customize',exact:true})).toHaveCount(0)
  const projectCard=await openSectionCard(page,'projects')
  await page.getByRole('button', { name: 'Projects: Card grid', exact: true }).click()
  await expect(page.getByLabel('Section heading size', { exact: true })).toHaveCount(0)
  await expect(page.getByLabel('Use general style', { exact: true })).toHaveCount(0)
  await expect(page.getByText('Section appearance', { exact: true })).toHaveCount(0)
  await openGeneralGroup(page,'Text sizes')
  await setControlValue(page.getByLabel('Section heading size', { exact: true }),40)
  await setControlValue(page.getByLabel('Introduction title size', { exact: true }),52)
  await setControlValue(page.getByLabel('Body text size', { exact: true }),18)
  await openGeneralGroup(page,'Spacing')
  await setControlValue(page.getByLabel('Section spacing', { exact: true }),64)
  await openSectionCard(page,'projects')
  await projectCard.getByText('Edit heading',{exact:true}).click()
  await page.getByLabel('Projects heading', { exact: true }).fill('Selected projects')
  const projects = page.locator('#editor-preview [data-section="projects"]')
  const about = page.locator('#editor-preview [data-section="experience"]')
  await expect(projects).toHaveAttribute('data-layout', 'cards')
  await expect(projects.locator('h2')).toHaveCSS('font-size', '40px')
  await expect(about).not.toHaveAttribute('data-section-heading', 'true')
  await expect(about.locator('h2')).toHaveCSS('font-size','40px')
  await expect(projects).toHaveCSS('padding-top','64px')
  await expect(projects).not.toHaveAttribute('data-section-accent','true')
  await expect(page.locator('#editor-preview h1')).toHaveCSS('font-size','52px')
  await projectCard.getByText('Image styling', { exact: true }).click()
  await expect(page.getByLabel('Project image proportions', { exact: true })).toBeVisible()
  await expect(projectCard.getByLabel('Personal photo size', { exact: true })).toHaveCount(0)
  await page.getByLabel('Project image color effect', { exact: true }).selectOption('grayscale')
  await page.getByLabel('Project image focal point', { exact: true }).selectOption('bottom')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-cover-effect', 'template')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-hero-position', 'center')
  await save(page)
  await page.reload()
  await openSectionCard(page,'projects')
  await expect(page.getByLabel('Section heading size', { exact: true })).toHaveCount(0)
  await expect(projects.locator('h2')).toHaveCSS('font-size','40px')
  const slug = `custom-${id.slice(0,8)}`
  expect((await page.request.put(`/api/documents/${id}/publication`, { headers, data: { slug, visibility: 'public' } })).status()).toBe(200)
  const visitor = await page.context().newPage()
  await visitor.goto(`/p/${slug}`)
  await expect(visitor.locator('[data-section="projects"] h2')).toHaveText('Selected projects')
  await expect(visitor.locator('[data-section="projects"] h2')).toHaveCSS('font-size', '40px')
  await page.screenshot({ path: testInfo.outputPath('portfolio-sections-desktop.png') })
  await expect(page.getByRole('button', { name: 'Reset to general style', exact: true })).toHaveCount(0)
  await expect(projects).not.toHaveAttribute('data-section-heading', 'true')
  const heroCard=await openSectionCard(page,'hero')
  await heroCard.getByText('Image styling', { exact: true }).click()
  await expect(page.getByLabel('Personal photo size', { exact: true })).toBeVisible()
  await expect(heroCard.getByLabel('Project image proportions', { exact: true })).toHaveCount(0)
  await page.getByRole('button',{name:'General',exact:true}).click()
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('portfolio-general-mobile.png') })
  expect(errors).toEqual([])
})
