import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { textDocument } from '../src/lib/summary.js'
const headers = { 'X-Linkfolio-Request':'1' }
test('spaced section cards keep heading, entry and footer actions usable', async ({ page }, testInfo) => {
  await page.request.post('/api/auth/register', { headers, data:{ fullName:'Section owner', email:`sections-${crypto.randomUUID()}@example.com`, password:'section password' } })
  const id = crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`, { headers, data:{ ...sampleProfile, id, kind:'resume', name:'Section controls', templateId:'essential', summarySection:{ heading:'Summary', entries:[{ id:'summary', visible:true, content:textDocument('Designing accessible tools for everyone.') }] } } })).status()).toBe(200)
  await page.setViewportSize({ width:1440, height:1000 })
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('button', { name:'Summary',exact:true }).click()
  await page.getByRole('button', { name:'Experience',exact:true }).click()
  const card = page.locator('.editor-entry-card').first()
  await card.getByRole('button', { name:'Edit heading',exact:true }).click()
  await card.getByLabel('Section heading', { exact:true }).fill('About me')
  await card.getByRole('button', { name:'Done heading',exact:true }).click()
  const renamed = page.locator('.editor-entry-card').filter({ has:page.getByRole('button', { name:'About me',exact:true }) })
  await renamed.getByRole('button', { name:'Hide summary entry 1',exact:true }).click()
  await expect(page.locator('#editor-preview')).not.toContainText('Designing accessible tools for everyone.')
  await renamed.getByRole('button', { name:'Show summary entry 1',exact:true }).click()
  await expect(page.locator('#editor-preview')).toContainText('Designing accessible tools for everyone.')
  await expect(renamed.getByRole('button',{name:'Actions for summary entry 1',exact:true})).toHaveCount(0)
  await renamed.getByRole('button', { name:'Delete summary entry 1',exact:true }).click()
  await expect(renamed.getByRole('button', { name:'Edit summary entry 1',exact:true })).toHaveCount(0)
  await page.getByRole('button', { name:'Undo deletion',exact:true }).click()
  for (const width of [1440,768,390,320]) {
    await page.setViewportSize({ width,height:1000 })
    await renamed.scrollIntoViewIfNeeded()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    const header = await renamed.locator('.entry-section-heading').boundingBox()
    const edit = await renamed.getByRole('button', { name:'Edit heading',exact:true }).boundingBox()
    expect(edit.y).toBeGreaterThanOrEqual(header.y)
    expect(edit.y + edit.height).toBeLessThanOrEqual(header.y + header.height)
    const footer = await renamed.locator('.entry-section-footer').boundingBox()
    const add = await renamed.getByRole('button', { name:'Add Entry',exact:true }).boundingBox()
    expect(Math.abs(add.x + add.width / 2 - footer.x - footer.width / 2)).toBeLessThan(2)
    await page.screenshot({ path:testInfo.outputPath(`section-actions-${width}.png`) })
  }
  await renamed.getByRole('button', { name:'Add Entry',exact:true }).click()
  await page.getByRole('button', { name:'Done',exact:true }).click()
  await expect(renamed.getByRole('button', { name:'Edit summary entry 2',exact:true })).toBeVisible()
  await renamed.getByRole('button', { name:'Remove section',exact:true }).click()
  await page.getByRole('button', { name:'Undo removal',exact:true }).click()
  await expect(page.getByRole('button', { name:'About me',exact:true })).toBeVisible()
  await page.getByRole('button', { name:'Save',exact:true }).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(page.getByRole('button', { name:'About me',exact:true })).toBeVisible()
})
