import { openGeneralGroup } from './helpers/designControls.js'
import { test, expect } from '@playwright/test'
import { sampleProfile } from '../src/components/resumeTemplates.js'
const headers = { 'X-Linkfolio-Request':'1' }
test('simple colors card applies each area and preserves choices',async({page},testInfo)=>{
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Color owner',email:`colors-${crypto.randomUUID()}@example.com`,password:'color testing password'}})
  const id=crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:{...sampleProfile,id,kind:'resume',name:'Colors',templateId:'classic'}})).status()).toBe(200)
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  const nav=page.getByRole('navigation',{name:'Design settings',exact:true})
  await openGeneralGroup(page,'Colors')
  const card=page.getByRole('region',{name:'Colors',exact:true})
  const paper=page.locator('#editor-preview .resume-page').first()
  await card.getByRole('button',{name:'Forest',exact:true}).click()
  await card.getByRole('checkbox',{name:'Name',exact:true}).check()
  await expect(paper.locator('header h2')).toHaveCSS('color','rgb(19, 119, 99)')
  await page.screenshot({path:testInfo.outputPath('colors-desktop.png')})
  await card.getByRole('button',{name:'Color area: Page',exact:true}).click()
  await card.getByRole('button',{name:'Mist',exact:true}).click()
  await expect(paper).toHaveCSS('background-color','rgb(237, 243, 239)')
  await card.getByRole('button',{name:'Color area: Header',exact:true}).click()
  await card.getByRole('button',{name:'Sky',exact:true}).click()
  await expect(paper.locator('header')).toHaveCSS('background-color','rgb(131, 204, 236)')
  await card.getByRole('button',{name:'Color area: Border',exact:true}).click()
  await card.getByRole('button',{name:'Ocean',exact:true}).click()
  await expect(paper).toHaveAttribute('data-page-border','custom')
  await expect(paper).toHaveCSS('border-top-color','rgb(36, 87, 120)')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(paper).toHaveCSS('background-color','rgb(237, 243, 239)')
  await expect(paper).toHaveCSS('border-top-color','rgb(36, 87, 120)')
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Colors')
  await card.getByRole('button',{name:'Reset colors',exact:true}).click()
  await expect(paper).toHaveAttribute('data-page-border','default')
  await expect(paper).toHaveCSS('background-color','rgb(255, 255, 255)')
  await page.setViewportSize({width:390,height:900})
  await openGeneralGroup(page,'Colors')
  await expect.poll(async()=>{const box=await card.boundingBox();return box.y>100 && box.y<400}).toBe(true)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('colors-mobile.png')})
})
