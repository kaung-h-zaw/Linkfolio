import { openGeneralGroup } from './helpers/designControls.js'
import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { getExperience } from '../src/lib/experience.js'
const headers={'X-Linkfolio-Request':'1'}
test('links and repeated footers save and export without covering content',async({page},testInfo)=>{
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Footer owner',email:`footer-${crypto.randomUUID()}@example.com`,password:'footer testing password'}})
  const id=crypto.randomUUID(),experience=getExperience(structuredClone(sampleProfile))
  experience.entries=Array.from({length:8},(_,index)=>({...experience.entries[0],id:`job-${index}`,jobTitle:`Designer ${index+1}`}))
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:{...sampleProfile,personal:{...sampleProfile.personal,links:[{id:'web',type:'Website',name:'',label:'example.com',url:'https://example.com'}]},experienceSection:experience,id,kind:'resume',name:'Links and footer',templateId:'classic'}})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  const links=page.getByRole('region',{name:'Links',exact:true}),footer=page.getByRole('region',{name:'Footer',exact:true})
  const pages=page.locator('#editor-preview .resume-page'),paper=pages.first(),web=paper.locator('header a').first()
  await openGeneralGroup(page,'Links')
  await expect(links.locator('details')).toHaveCount(0)
  await links.getByRole('checkbox',{name:'Underline',exact:true}).uncheck()
  await expect(web).toHaveCSS('text-decoration-line','none')
  await links.getByRole('checkbox',{name:'Blue color',exact:true}).check()
  await expect(web).toHaveCSS('color','rgb(37, 99, 235)')
  await links.getByRole('checkbox',{name:'Link icon',exact:true}).check()
  await links.getByRole('button',{name:'Link icon style: External link',exact:true}).click()
  await expect(paper).toHaveAttribute('data-link-icon','external')
  expect(await web.evaluate(node=>getComputedStyle(node,'::after').backgroundImage)).toContain('data:image/svg+xml')
  await openGeneralGroup(page,'Footer')
  for(const label of ['Page numbers','Email','Name'])await footer.getByRole('checkbox',{name:label,exact:true}).check()
  await expect.poll(()=>pages.count()).toBeGreaterThan(1)
  await expect.poll(async()=>pages.locator('.resume-page-footer').count()).toBe(await pages.count())
  const count=await pages.count()
  for(let index=0;index<count;index++){
    const article=pages.nth(index),pageFooter=article.locator('.resume-page-footer')
    await expect(pageFooter).toContainText(sampleProfile.personal.fullName)
    await expect(pageFooter).toContainText(sampleProfile.personal.email)
    await expect(pageFooter.locator('.resume-page-number')).toHaveText(`${index+1} / ${count}`)
    const footerBox=await pageFooter.boundingBox(),paperBox=await article.boundingBox()
    expect(footerBox.y+footerBox.height).toBeLessThan(paperBox.y+paperBox.height)
    const emailBox=await pageFooter.locator('.resume-footer-email').boundingBox()
    expect(Math.abs(emailBox.x+emailBox.width/2-(paperBox.x+paperBox.width/2))).toBeLessThan(2)
    await expect(pageFooter.locator('.resume-footer-email')).toHaveCSS('text-align','center')
    await expect(pageFooter.locator('.resume-page-number')).toHaveCSS('text-align','right')
    for(const child of await article.locator(':scope > section,:scope > header').all()){
      const box=await child.boundingBox()
      expect(box.y+box.height).toBeLessThan(footerBox.y)
    }
  }
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(paper).toHaveAttribute('data-link-icon','external')
  await expect(paper.locator('.resume-page-footer')).toContainText(sampleProfile.personal.email)
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download resume',exact:true}).click()
  const download=await downloadEvent
  await download.saveAs(testInfo.outputPath('links-footer.pdf'))
  expect(await download.failure()).toBeNull()
  const {getDocument}=await import('pdfjs-dist/legacy/build/pdf.mjs'),{readFile}=await import('node:fs/promises')
  const pdf=await getDocument({data:new Uint8Array(await readFile(testInfo.outputPath('links-footer.pdf'))),useSystemFonts:true}).promise
  expect(pdf.numPages).toBe(count)
  expect((await (await pdf.getPage(1)).getAnnotations()).some(item=>item.url?.includes('example.com'))).toBe(true)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Footer')
  await footer.screenshot({path:testInfo.outputPath('footer-desktop.png')})
  await pages.last().locator('.resume-page-footer').screenshot({path:testInfo.outputPath('resume-footer.png')})
  await footer.getByRole('button',{name:'Reset footer',exact:true}).click()
  await expect(pages.locator('.resume-page-footer')).toHaveCount(0)
  await expect(paper).toHaveAttribute('data-link-icon','external')
  await page.setViewportSize({width:390,height:900})
  await openGeneralGroup(page,'Links')
  await links.screenshot({path:testInfo.outputPath('links-mobile.png')})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await links.getByRole('button',{name:'Reset links',exact:true}).click()
  await expect(links.getByRole('checkbox',{name:'Underline',exact:true})).toBeChecked()
})
