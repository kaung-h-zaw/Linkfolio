import { test,expect } from '@playwright/test'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { textDocument } from '../src/lib/summary.js'
import { getSkills } from '../src/lib/educationSkills.js'
import { newLanguage } from '../src/lib/additionalSections.js'
import { openSectionCard } from './helpers/designControls.js'
const headers={'X-Linkfolio-Request':'1'}
test('collection styles apply inline details, separators, spacing without level styles',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Collections owner',email:`collections-${crypto.randomUUID()}@example.com`,password:'collections test password'}})
  const id=crypto.randomUUID(),skills=getSkills(structuredClone(sampleProfile))
  skills.entries=skills.entries.slice(0,3).map((item,index)=>({...item,name:['Frameworks','Styling','Tools'][index],content:textDocument(['React, Node.js','Tailwind CSS','Git, Figma'][index])}))
  const profile={...sampleProfile,id,kind:'resume',name:'Collection styles',templateId:'essential',skillsSection:skills,languagesSection:{heading:'Languages',entries:[{...newLanguage(),name:'English',level:'Fluent'},{...newLanguage(),name:'Burmese',level:'Native/Bilingual'}]}}
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:profile})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  let card=await openSectionCard(page,'skills')
  await expect(page.locator('[data-section-customization=summary]')).toHaveCount(0)
  const grid=page.locator('#editor-preview .resume-page [data-section=skills] .resume-section-collection').first()
  await card.getByRole('button',{name:'Skills style: Rows',exact:true}).click()
  await card.getByRole('button',{name:'Skills Row spacing: Spacious',exact:true}).click()
  await expect(grid).toHaveCSS('row-gap','14px')
  await card.getByRole('checkbox',{name:'Start rows with bullets',exact:true}).check()
  expect(await grid.locator(':scope > *').first().evaluate(node=>getComputedStyle(node,'::before').content)).toContain('•')
  expect(await grid.locator(':scope > *').first().evaluate(node=>getComputedStyle(node,'::before').position)).toBe('static')
  await card.getByRole('button',{name:'Skills Subinfo style: : Colon',exact:true}).click()
  const details=grid.locator('.resume-collection-subinfo').first()
  await expect(details).toHaveCSS('display','inline')
  expect(await details.evaluate(node=>getComputedStyle(node,'::before').content)).toContain(':')
  await card.screenshot({path:testInfo.outputPath('rows-controls.png')})
  await grid.screenshot({path:testInfo.outputPath('rows-preview.png')})
  await card.getByRole('button',{name:'Skills style: Compact',exact:true}).click()
  await card.getByRole('button',{name:'Skills Separator: Comma',exact:true}).click()
  await expect(grid).toHaveCSS('display','block')
  await expect(grid.locator(':scope > *').first()).toHaveCSS('display','inline')
  expect(await grid.locator(':scope > *').nth(1).evaluate(node=>getComputedStyle(node,'::before').content)).toContain(',')
  await card.getByRole('button',{name:'Skills Subinfo style: () Bracket',exact:true}).click()
  expect(await details.evaluate(node=>getComputedStyle(node,'::before').content)).toContain('(')
  expect(await details.evaluate(node=>getComputedStyle(node,'::after').content)).toContain(')')
  await grid.screenshot({path:testInfo.outputPath('compact-preview.png')})
  await card.getByRole('button',{name:'Skills style: Bubble',exact:true}).click()
  await expect(grid).toHaveCSS('display','flex')
  await expect(grid.locator(':scope > *').first()).toHaveCSS('border-top-style','solid')
  await grid.screenshot({path:testInfo.outputPath('bubble-preview.png')})
  await expect(card.getByRole('button',{name:'Skills style: Level',exact:true})).toHaveCount(0)
  card=await openSectionCard(page,'languages')
  await expect(card.getByRole('button',{name:'Languages style: Level',exact:true})).toHaveCount(0)
  await card.getByRole('button',{name:'Languages style: Rows',exact:true}).click()
  await card.getByRole('button',{name:'Languages Subinfo style: – Dash',exact:true}).click()
  card=await openSectionCard(page,'certifications')
  await card.getByRole('button',{name:'Certifications style: Compact',exact:true}).click()
  await card.getByRole('button',{name:'Certifications Separator: Pipe',exact:true}).click()
  await expect(page.locator('#editor-preview .resume-page [data-section=certifications] .resume-certification-item')).toContainText('Design Learning Academy')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(grid).toHaveAttribute('data-collection-layout','tags')
  await expect(page.locator('#editor-preview .resume-page [data-section=certifications] .resume-section-collection')).toHaveAttribute('data-compact-separator','pipe')
  const saved=(await (await page.request.get('/api/documents')).json()).documents.find(item=>item.id===id)
  expect(saved.skillsSection.entries[0].content).toEqual(skills.entries[0].content)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  card=await openSectionCard(page,'languages')
  await page.setViewportSize({width:320,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await card.screenshot({path:testInfo.outputPath('languages-mobile.png')})
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download resume',exact:true}).click();const download=await downloadEvent;await download.saveAs(testInfo.outputPath('collection-styles.pdf'));expect(await download.failure()).toBeNull()
  expect(errors).toEqual([])
})
