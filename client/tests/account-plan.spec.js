import { test, expect } from './fixtures.js'

test('upgrades live in Premium, plan removal and sign out live in Account', async ({ page }, testInfo) => {
  const headers = { 'X-Linkfolio-Request': '1' }
  const result = await page.request.post('/api/auth/register', { headers, data: { fullName: 'Account Tester', email: `account-${crypto.randomUUID()}@example.com`, password: 'account test password' } })
  expect(result.status()).toBe(201)
  await page.goto('/setup')
  const sidebar = page.getByRole('complementary')
  await expect(sidebar.getByRole('button', { name: 'Sign out', exact: true })).toHaveCount(0)
  await expect(sidebar.getByRole('link', { name: 'Back to Linkfolio', exact: true })).toHaveCount(0)
  await expect(sidebar.getByRole('link', { name: 'Linkfolio dashboard', exact: true })).toHaveAttribute('href', '/dashboard')
  await sidebar.getByRole('link', { name: 'Upgrade to Premium', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Free', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Try demo upgrade', exact: true }).click()
  await page.getByRole('button', { name: 'Simulate successful payment', exact: true }).click()
  await expect(page.getByText('Demo payment successful. Premium is active.', { exact: true })).toBeVisible()
  await expect(sidebar.getByRole('link', { name: 'Upgrade to Premium', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Manage your plan in Account', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Remove Premium', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Sign out', exact: true })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('account-premium.png'), fullPage: true })
  await page.getByRole('button', { name: 'Remove Premium', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: 'Switch to Free?', exact: true })
  await expect(confirmation).toBeVisible()
  await expect(confirmation.getByRole('button', { name: 'Keep Premium', exact: true })).toBeFocused()
  await page.screenshot({ path: testInfo.outputPath('premium-confirmation-desktop.png') })
  await confirmation.getByRole('button', { name: 'Keep Premium', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Remove Premium', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Remove Premium', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(confirmation).toHaveCount(0)
  await page.getByRole('button', { name: 'Remove Premium', exact: true }).click()
  await page.route('**/api/billing/downgrade', (route) => route.fulfill({ status: 503, json: { error: 'Please try again.' } }))
  await confirmation.getByRole('button', { name: 'Switch to Free', exact: true }).click()
  await expect(confirmation.getByRole('alert')).toContainText('Please try again.')
  await expect(confirmation).toBeVisible()
  await page.unroute('**/api/billing/downgrade')
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('premium-confirmation-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await confirmation.getByRole('button', { name: 'Switch to Free', exact: true }).click()
  await expect(confirmation).toHaveCount(0)
  await expect(page.getByText('Premium removed. Your account is now on the Free plan.', { exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: 'Remove Premium', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Open workspace menu', exact: true }).click()
  await expect(sidebar.getByRole('link', { name: 'Upgrade to Premium', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close workspace menu', exact: true }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('account-free-mobile.png'), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  await expect(page).toHaveURL('/')
  expect((await page.request.get('/api/auth/me')).status()).toBe(401)
})
