import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { defaultPortfolio } from '../src/lib/portfolio.js'
import { getProjects } from '../src/lib/additionalSections.js'

const headers = { 'X-Linkfolio-Request':'1' }
test('portfolio workspace offers a compact creation flow and creates a separate copy from a resume', async ({ page },testInfo) => {
  expect((await page.request.post('/api/auth/register',{headers,data:{fullName:'Portfolio Owner',email:`create-${crypto.randomUUID()}@example.com`,password:'portfolio test password'}})).status()).toBe(201)
  await page.goto('/setup?view=portfolio')
  await expect(page.getByRole('heading',{name:'No portfolios yet'})).toBeVisible()
  await page.getByRole('button',{name:'Create portfolio',exact:true}).click()
  const dialog = page.getByRole('dialog',{name:'Create a portfolio',exact:true})
  await expect(dialog.getByText('Save or import a resume to use this option.')).toBeVisible()
  await dialog.getByRole('button',{name:/Start fresh/}).click()
  await expect(page).toHaveURL(/\/portfolio\/editor\/design$/)
  await page.goto('/premium')
  await page.getByRole('button',{name:'Try demo upgrade',exact:true}).click()
  await page.getByRole('button',{name:'Simulate successful payment',exact:true}).click()
  await page.getByText('Demo payment successful. Premium is active.',{exact:true}).waitFor()
  const id = crypto.randomUUID()
  const resume = {...sampleProfile,id,kind:'resume',name:'My saved resume',templateId:'essential',portfolio:defaultPortfolio}
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:resume})).status()).toBe(200)
  await page.goto('/setup?view=portfolio')
  await expect(page.getByRole('link',{name:/Edit portfolio for/})).toHaveCount(1)
  await expect(page.getByText('New portfolio',{exact:true})).toHaveCount(0)
  await page.screenshot({path:testInfo.outputPath('portfolio-workspace-desktop.png'),fullPage:true})
  await page.getByRole('button',{name:'Create portfolio',exact:true}).click()
  await expect(dialog.getByLabel('Choose a resume')).toHaveValue(id)
  await page.screenshot({path:testInfo.outputPath('create-portfolio-desktop.png')})
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button',{name:'Create portfolio',exact:true})).toBeFocused()
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'Create portfolio',exact:true}).click()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('create-portfolio-mobile.png')})
  await dialog.getByRole('button',{name:'Create from resume',exact:true}).click()
  await expect(page).toHaveURL(/\/portfolio\/editor\?resume=/)
  const createdId = new URL(page.url()).searchParams.get('resume')
  expect(createdId).not.toBe(id)
  const {documents} = await (await page.request.get('/api/documents')).json()
  const source = documents.find((item) => item.id === id)
  const created = documents.find((item) => item.id === createdId)
  expect(created.portfolio.sourceResume).toEqual({id,name:source.name})
  await expect(page.getByRole('button',{name:'Edit resume',exact:true})).toBeVisible()
  await expect(page.getByLabel('Resume',{exact:true})).toHaveValue(id)
  await expect(page.locator('#editor-content')).toContainText(source.name)
  await page.reload()
  await expect(page.getByRole('button',{name:'Edit resume',exact:true})).toBeVisible()
  await expect(page.getByLabel('Resume',{exact:true})).toHaveValue(id)
  expect(created.kind).toBe('portfolio')
  expect(created.personal).toMatchObject(source.personal)
  expect(source.personal).toEqual(resume.personal)
  expect(created.projectsSection).toEqual(getProjects(source))
  expect(created.publication.slug).not.toBe(source.publication.slug)
  expect(source.kind).toBe('resume')
})
