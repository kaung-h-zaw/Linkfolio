import { openGeneralGroup } from './helpers/designControls.js'
import { test, expect } from '@playwright/test'
import { fileURLToPath } from 'node:url'
import { sampleProfile } from '../src/components/resumeTemplates.js'
const headers={'X-Linkfolio-Request':'1'}
test('header and photo choices update preview, save and reset independently',async({page},testInfo)=>{
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Header owner',email:`header-${crypto.randomUUID()}@example.com`,password:'header testing password'}})
  const id=crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:{...sampleProfile,personal:{...sampleProfile.personal,links:[{id:'gh',type:'GitHub',name:'',label:'GitHub',url:'https://github.com/example'},{id:'in',type:'LinkedIn',name:'',label:'LinkedIn',url:'https://www.linkedin.com/in/example'},{id:'web',type:'Website',name:'',label:'Website',url:'https://example.com'},{id:'other',type:'GitHub',name:'',label:'Other',url:'https://github.com.example.com'}]},id,kind:'resume',name:'Header and photo',templateId:'classic'}})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  const nav=page.getByRole('navigation',{name:'Design settings',exact:true})
  const card=page.getByRole('region',{name:'Header',exact:true}),photoCard=page.getByRole('region',{name:'Photo',exact:true})
  const paper=page.locator('#editor-preview .resume-page').first(),header=paper.locator('header'),photo=header.locator('.resume-photo')
  await openGeneralGroup(page,'Header')
  for(const [label,alignment] of [['Left','left'],['Center','center']]) {
    await card.getByRole('button',{name:`Text alignment: ${label}`,exact:true}).click()
    await expect(header).toHaveCSS('text-align',alignment)
  }
  for(const [label,display] of [['Stacked','flex'],['Inline','flex'],['Two columns','grid']]) {
    await card.getByRole('button',{name:`Contact details: ${label}`,exact:true}).click()
    await expect(header.locator('.resume-contact-details')).toHaveCSS('display',display)
  }
  await card.getByRole('button',{name:'Contact icons: Soft',exact:true}).click()
  await expect(header.locator('.resume-contact-icon').first()).toBeVisible()
  await expect(header.locator('[data-service="GitHub"] svg')).toBeVisible()
  await expect(header.locator('[data-service="LinkedIn"] svg')).toBeVisible()
  await expect(header.locator('a[href="https://example.com/"] .resume-contact-icon svg')).toBeVisible()
  await expect(header.locator('a[href="https://github.com.example.com/"] [data-service]')).toHaveCount(0)
  await card.getByRole('button',{name:'Name style: Bold',exact:true}).click()
  await expect(header.locator('h2')).toHaveCSS('font-weight','700')
  await card.getByRole('button',{name:'Job title style: Italic',exact:true}).click()
  await expect(header.locator(':scope > p')).toHaveCSS('font-style','italic')
  await card.getByRole('button',{name:'Job title position: Beside name',exact:true}).click()
  await expect(header.locator('h2')).toHaveCSS('display','inline')
  await page.screenshot({path:testInfo.outputPath('header-desktop.png')})
  await openGeneralGroup(page,'Photo')
  await photoCard.getByRole('checkbox',{name:'Show photo',exact:true}).check()
  await expect(photo).toBeVisible()
  await expect(header).toHaveAttribute('data-photo-position','top')
  await photoCard.getByRole('checkbox',{name:'Grayscale',exact:true}).check()
  await expect(photo).toHaveCSS('filter','grayscale(1)')
  await expect(photoCard.getByRole('button',{name:'Photo position: Left',exact:true})).toBeDisabled()
  await expect(photoCard.getByRole('button',{name:'Photo position: Right',exact:true})).toBeDisabled()
  await photoCard.getByRole('group',{name:'Left photo position unavailable',exact:true}).hover()
  await expect(photoCard.getByRole('tooltip')).toContainText('Set text alignment to Left in Header.')
  await card.getByRole('button',{name:'Text alignment: Left',exact:true}).click()
  await expect(header).toHaveAttribute('data-photo-position','right')
  await expect(photoCard.getByRole('button',{name:'Photo position: Top',exact:true})).toBeDisabled()
  await photoCard.getByRole('group',{name:'Top photo position unavailable',exact:true}).focus()
  await expect(photoCard.getByRole('tooltip')).toContainText('Set text alignment to Center in Header.')
  for(const [label,position] of [['Left','left'],['Right','right']]) {
    await photoCard.getByRole('button',{name:`Photo position: ${label}`,exact:true}).click()
    await expect(header).toHaveAttribute('data-photo-position',position)
    if(position==='top') await expect(photo).toHaveCSS('position','static')
    else {
      await expect(paper).toHaveAttribute('data-header','left')
      await expect(card.getByRole('button',{name:'Text alignment: Left',exact:true})).toHaveAttribute('aria-pressed','true')
      const imageBox=await photo.boundingBox(),nameBox=await header.locator('h2').boundingBox()
      expect(position==='left'?imageBox.x+imageBox.width<nameBox.x:imageBox.x>nameBox.x+nameBox.width).toBe(true)
    }
  }
  await card.getByRole('button',{name:'Text alignment: Center',exact:true}).click()
  await expect(header).toHaveAttribute('data-photo-position','top')
  await expect(photoCard.getByRole('button',{name:'Photo position: Top',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(photo).toHaveCSS('position','static')
  const centeredPhoto=await photo.boundingBox(),centeredHeader=await header.boundingBox()
  expect(Math.abs(centeredPhoto.x+centeredPhoto.width/2-(centeredHeader.x+centeredHeader.width/2))).toBeLessThan(2)
  await expect(photoCard.getByRole('button',{name:'Photo position: Left',exact:true})).toBeDisabled()
  await expect(photoCard.getByRole('button',{name:'Photo position: Right',exact:true})).toBeDisabled()
  await card.getByRole('button',{name:'Text alignment: Left',exact:true}).click()
  await expect(photoCard.getByRole('button',{name:'Photo position: Top',exact:true})).toBeDisabled()
  await photoCard.getByRole('button',{name:'Photo position: Right',exact:true}).click()
  await expect(paper).toHaveAttribute('data-header','left')
  await photoCard.getByRole('button',{name:'Photo size: L',exact:true}).click()
  await expect(header).toHaveAttribute('data-photo-size','l')
  await photoCard.getByRole('button',{name:'Photo shape: Rounded',exact:true}).click()
  await expect(photo).toHaveCSS('border-top-left-radius','12px')
  await photoCard.getByRole('checkbox',{name:'Show photo',exact:true}).uncheck()
  await expect(photo).toHaveCount(0)
  await photoCard.getByRole('checkbox',{name:'Show photo',exact:true}).check()
  await photoCard.getByRole('button',{name:'Change photo',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Personal details',exact:true})).toBeVisible()
  await page.getByLabel('Resume photo (optional)',{exact:true}).setInputFiles(fileURLToPath(new URL('../public/images/resume-demo.jpg',import.meta.url)))
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Photo')
  await expect(photo).toHaveAttribute('src',/^data:image\/jpeg;base64,/)
  await page.screenshot({path:testInfo.outputPath('photo-desktop.png')})
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(header).toHaveAttribute('data-contact-icons','soft')
  await expect(header).toHaveAttribute('data-photo-shape','rounded')
  await expect(photo).toHaveCSS('filter','grayscale(1)')
  await expect(photo).toHaveAttribute('src',/^data:image\/jpeg;base64,/)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Photo')
  await photoCard.getByRole('button',{name:'Reset photo design',exact:true}).click()
  await expect(photo).toHaveCount(0)
  await expect(header).toHaveAttribute('data-contact-icons','soft')
  await openGeneralGroup(page,'Header')
  await card.getByRole('button',{name:'Reset header',exact:true}).click()
  await expect(header.locator('.resume-contact-icon')).toHaveCount(0)
  await page.setViewportSize({width:390,height:1000})
  await openGeneralGroup(page,'Header')
  await expect.poll(async()=>{const box=await card.boundingBox();return box.y>100&&box.y<400}).toBe(true)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('header-mobile.png')})
  await openGeneralGroup(page,'Photo')
  await photoCard.getByRole('checkbox',{name:'Show photo',exact:true}).check()
  await expect.poll(async()=>{const box=await photoCard.boundingBox();return box.y>100&&box.y<400}).toBe(true)
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('photo-mobile.png')})
  await photoCard.getByRole('button',{name:'Change photo',exact:true}).click()
  await page.getByRole('button',{name:'Remove photo',exact:true}).click()
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Photo')
  await expect(photoCard.getByText('Add a photo in Personal details to style it here.')).toBeVisible()
  await expect(photoCard.getByRole('checkbox')).toHaveCount(0)
  await expect(photoCard.locator('input[type=file]')).toHaveCount(0)
  await photoCard.screenshot({path:testInfo.outputPath('photo-empty-mobile.png')})
  await photoCard.getByRole('button',{name:'Personal details',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Personal details',exact:true})).toBeVisible()
  await page.getByLabel('Resume photo (optional)',{exact:true}).setInputFiles(fileURLToPath(new URL('../public/images/resume-demo.jpg',import.meta.url)))
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Photo')
  await expect(photoCard.getByRole('checkbox',{name:'Show photo',exact:true})).toBeChecked()
})
