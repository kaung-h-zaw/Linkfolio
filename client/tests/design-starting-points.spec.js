import { openGeneralGroup } from './helpers/designControls.js'
import { test, expect } from '@playwright/test'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { defaultPortfolio } from '../src/lib/portfolio.js'
import { portfolioDemoImages } from '../src/lib/portfolioImages.js'
import { getProjects } from '../src/lib/additionalSections.js'
import { getExperience } from '../src/lib/experience.js'

const headers = { 'X-Linkfolio-Request': '1' }
async function createDocument(page, kind, extra = {}) {
  expect((await page.request.post('/api/auth/register', { headers, data: { fullName: 'Alex Morgan', email: `design-${crypto.randomUUID()}@example.com`, password: 'design test password' } })).status()).toBe(201)
  const id = crypto.randomUUID()
  const response = await page.request.put(`/api/documents/${id}`, { headers, data: { ...sampleProfile, id, kind, name: 'Design study', templateId: 'essential', portfolio: { ...defaultPortfolio, introduction: 'I turn complex problems into clear, useful digital experiences.' }, ...extra } })
  expect(response.status()).toBe(200)
  return id
}
async function save(page) {
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByText('Saved to your account', { exact: true }).first()).toBeVisible()
}

test('resume essentials, spacing history, group reset, persistence and paginated PDF', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const experience = getExperience(structuredClone(sampleProfile))
  experience.entries = Array.from({ length: 8 }, (_, index) => ({ ...experience.entries[0], id: `job-${index}`, jobTitle: `Product Designer ${index + 1}` }))
  const id = await createDocument(page, 'resume', { experienceSection: experience })
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('button', { name: 'Design', exact: true }).click()
  const modernFont = page.getByRole('combobox', { name:'Body font',exact:true })
  await expect(page.getByLabel('Body size', { exact: true })).toBeVisible()
  await modernFont.selectOption('Arial, sans-serif')
  await page.getByRole('button', { name: 'Forest', exact: true }).click()
  await page.getByRole('button', { name: 'One column layout', exact: true }).click()
  await page.getByRole('button', { name: 'Balanced spacing', exact: true }).click()
  await expect(modernFont).toHaveValue('Arial, sans-serif')
  const paper = page.locator('#editor-preview .resume-page').first()
  await expect(paper).toHaveCSS('--resume-accent', '#137763')
  await expect(paper).toHaveAttribute('data-columns', 'one')
  await expect.poll(() => page.locator('#editor-preview .resume-page').count()).toBeGreaterThan(1)
  await expect(page.locator('#editor-preview .resume-page h4').filter({ hasText: /^Product Designer \d+$/ })).toHaveCount(8)
  await page.getByRole('button', { name: 'Compact spacing', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Compact spacing', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Undo styling', exact: false }).click()
  await expect(page.getByRole('button', { name: 'Balanced spacing', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Redo styling', exact: false }).click()
  await expect(page.getByRole('button', { name: 'Compact spacing', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Balanced spacing', exact: true }).click()
  await save(page)
  await page.screenshot({ path: testInfo.outputPath('resume-design-desktop.png') })
  await paper.screenshot({ path: testInfo.outputPath('signature-resume.png') })
  await page.reload()
  await page.getByRole('button', { name: 'Design', exact: true }).click()
  await expect(modernFont).toHaveValue('Arial, sans-serif')
  await openGeneralGroup(page,'Text sizes')
  await page.getByRole('button', { name: 'Increase Name size', exact: true }).click()
  await expect(page.getByLabel('Name size', { exact: true })).toHaveValue('29')
  await page.getByRole('button', { name: 'Reset font size', exact: true }).click()
  await expect(page.getByLabel('Name size', { exact: true })).toHaveValue('28')
  await expect(paper).toHaveCSS('--resume-accent', '#137763')
  await page.getByRole('button', { name: 'Undo styling', exact: false }).click()
  await expect(page.getByLabel('Name size', { exact: true })).toHaveValue('29')
  const downloadEvent = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Download resume', exact: true }).click()
  const download = await downloadEvent
  await download.saveAs(testInfo.outputPath('signature-resume.pdf'))
  expect(await download.failure()).toBeNull()
  const { getDocument } = await import('pdfjs-dist/legacy/build/pdf.mjs')
  const { readFile } = await import('node:fs/promises')
  const pdf = await getDocument({ data: new Uint8Array(await readFile(testInfo.outputPath('signature-resume.pdf'))), useSystemFonts: true }).promise
  expect(pdf.numPages).toBeGreaterThan(1)
  expect((await pdf.getMetadata()).info.Title).toContain('Alex Morgan')
  expect((await (await pdf.getPage(1)).getOperatorList()).fnArray.length).toBeGreaterThan(5)
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(modernFont).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('resume-design-mobile.png') })
  expect(errors).toEqual([])
})

test('portfolio essentials preserve content, undo styles, publish and adapt to missing images', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', (error) => errors.push(error.message))
  const projects = getProjects(sampleProfile)
  const id = await createDocument(page, 'portfolio', { portfolio: { ...defaultPortfolio, introduction: 'I turn complex problems into clear, useful digital experiences.', images: { portrait: portfolioDemoImages.portrait, projects: Object.fromEntries(projects.entries.map((item) => [item.id, portfolioDemoImages.projectCovers[0]])) } } })
  await page.goto(`/portfolio/editor/design?resume=${id}`)
  await page.getByText('Choose portfolio template', { exact: true }).click()
  await page.getByRole('button', { name: 'Use Clear template', exact: true }).click()
  await page.getByText('Choose portfolio template', { exact: true }).click()
  const modernFont = page.getByRole('button', { name: 'Modern font', exact: true })
  await expect(page.getByLabel('Portfolio font', { exact: true })).toBeHidden()
  await expect(page.getByRole('button', { name: 'Use template accent', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Forest', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Use template accent', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-custom-accent', 'true')
  await modernFont.click()
  await expect(modernFont).toHaveAttribute('aria-pressed', 'true')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-web-source', 'miniport')
  await page.getByRole('button', { name: 'Classic font', exact: true }).click()
  await page.getByRole('button', { name: 'Undo styling', exact: false }).click()
  await expect(modernFont).toHaveAttribute('aria-pressed', 'true')
  // Content edits must survive undoing a style change.
  await page.getByRole('button', { name: 'Content', exact: true }).click()
  await page.getByLabel('Availability', { exact: true }).selectOption('Available for freelance')
  await page.getByRole('button', { name: 'Design', exact: true }).click()
  await page.getByRole('button', { name: 'Undo styling', exact: false }).click()
  await expect(page.locator('#editor-preview .portfolio-availability')).toHaveText('Available for freelance')
  await page.getByRole('button', { name: 'Redo styling', exact: false }).click()
  await expect(modernFont).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('tab', { name: /^Sections/ }).click()
  await page.locator('[data-section-choice=hero]').click()
  await page.getByRole('button', { name: 'Introduction: Split introduction', exact: true }).click()
  await page.locator('[data-section-choice=projects]').click()
  await page.getByRole('button', { name: 'Projects: Card grid', exact: true }).click()
  await page.getByRole('tab', { name: /^General/ }).click()
  await page.getByRole('button', { name: 'Balanced spacing', exact: true }).click()
  await page.screenshot({ path: testInfo.outputPath('portfolio-design-desktop.png') })
  await save(page)
  await page.reload()
  await expect(modernFont).toHaveAttribute('aria-pressed', 'true')
  const slug = `signature-${id.slice(0, 8)}`
  expect((await page.request.put(`/api/documents/${id}/publication`, { headers, data: { slug, visibility: 'public' } })).status()).toBe(200)
  const visitor = await page.context().newPage()
  await visitor.goto(`/p/${slug}`)
  await visitor.screenshot({ path: testInfo.outputPath('signature-portfolio-desktop.png'), fullPage: true })
  await visitor.screenshot({ path: testInfo.outputPath('signature-portfolio-hero-desktop.png') })
  await visitor.setViewportSize({ width: 390, height: 844 })
  expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await visitor.screenshot({ path: testInfo.outputPath('signature-portfolio-mobile.png'), fullPage: true })
  await visitor.screenshot({ path: testInfo.outputPath('signature-portfolio-hero-mobile.png') })
  // Remove all photos through the document API, then check the public fallback.
  const documents = await (await page.request.get('/api/documents')).json()
  const savedDocument = documents.documents.find((document) => document.id === id)
  expect((await page.request.put(`/api/documents/${id}`, { headers, data: { ...savedDocument, personal: { ...savedDocument.personal, photo: '' }, portfolio: { ...savedDocument.portfolio, images: {} } } })).status()).toBe(200)
  await visitor.reload()
  await expect(visitor.locator('.portfolio-portrait')).toHaveCount(0)
  await expect(visitor.locator('.portfolio-project-image')).toHaveCount(0)
  await expect(visitor.getByRole('heading', { level: 1 })).toBeVisible()
  await visitor.setViewportSize({ width: 1440, height: 1000 })
  expect(await visitor.locator('.portfolio-hero').evaluate((hero) => getComputedStyle(hero).gridTemplateColumns.split(' ').length)).toBe(1)
  await visitor.screenshot({ path: testInfo.outputPath('signature-portfolio-without-images.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(modernFont).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('portfolio-design-mobile.png') })
  expect(errors).toEqual([])
})
