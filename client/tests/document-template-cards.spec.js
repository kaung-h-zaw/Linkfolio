import { test, expect } from '@playwright/test'
import { sampleProfile } from '../src/components/resumeTemplates.js'
const headers = { 'X-Linkfolio-Request':'1' }

test('document and template cards update the preview, save settings and fit small screens', async ({ page }, testInfo) => {
  await page.request.post('/api/auth/register', { headers, data:{ fullName:'Design owner', email:`document-cards-${crypto.randomUUID()}@example.com`, password:'document password' } })
  const id = crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`, { headers, data:{ ...sampleProfile, id, kind:'resume', name:'Design cards', templateId:'essential' } })).status()).toBe(200)
  await page.setViewportSize({ width:1440, height:1000 })
  await page.goto(`/editor?resume=${id}`)
  const nav = page.getByRole('navigation', { name:'Editor navigation', exact:true })
  await nav.getByRole('button', { name:'Design', exact:true }).click()
  const document = page.getByRole('region', { name:'Document settings', exact:true })
  const templates = page.getByRole('region', { name:'Templates', exact:true })
  await expect(document.getByRole('combobox')).toHaveCount(3)
  await document.getByLabel('Language', { exact:true }).selectOption('fr-FR')
  await document.getByLabel('Date format', { exact:true }).selectOption('long')
  await document.getByLabel('Page size', { exact:true }).selectOption('Letter')
  const paper = page.locator('#editor-preview .resume-page').first()
  await expect(paper).toHaveAttribute('lang','fr-FR')
  await expect(paper).toContainText('janvier 2023')
  await expect(paper).toHaveCSS('--design-ratio','8.5 / 11')
  await page.getByRole('button', { name:'Save', exact:true }).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await nav.getByRole('button', { name:'Design', exact:true }).click()
  await expect(document.getByLabel('Language', { exact:true })).toHaveValue('fr-FR')
  await expect(document.getByLabel('Page size', { exact:true })).toHaveValue('Letter')
  await templates.getByRole('button', { name:'Browse templates', exact:true }).click()
  const picker = page.getByRole('dialog', { name:'Choose a template', exact:true })
  await picker.getByRole('button', { name:/^Harvard/ }).click()
  await expect(picker).toHaveCount(0)
  await expect(paper).toHaveAttribute('data-template','classic')
  await expect(templates.locator('.resume-template-current')).toHaveText('Harvard')
  await document.getByRole('button', { name:'Reset document settings', exact:true }).click()
  await expect(document.getByLabel('Language', { exact:true })).toHaveValue('en-GB')
  await expect(document.getByLabel('Page size', { exact:true })).toHaveValue('A4')
  for (const width of [1440,768,390,320]) {
    await page.setViewportSize({ width,height:1000 })
    await page.locator('#editor-content').evaluate((element) => element.scrollTo(0,0))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const card of [document, templates]) expect(await card.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({ path:testInfo.outputPath(`document-template-cards-${width}.png`) })
  }
})
