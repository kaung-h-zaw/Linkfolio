import { test, expect } from './fixtures.js'

test('resume workspace offers new and import choices on desktop and mobile', async ({ page }, testInfo) => {
  const result = await page.request.post('/api/auth/register', {
    headers: { 'X-Linkfolio-Request': '1' },
    data: { fullName: 'Resume Creator', email: `creator-${crypto.randomUUID()}@example.com`, password: 'resume creation password' },
  })
  expect(result.status()).toBe(201)
  await page.goto('/setup')
  await expect(page.getByRole('heading', { name: 'My resumes', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'No resumes yet' })).toBeVisible()
  await expect(page.getByRole('button', { name: /^Preview .* template$/ })).toHaveCount(0)
  const create = page.getByRole('button', { name: 'Create resume', exact: true })
  await create.click()
  const chooser = page.getByRole('dialog', { name: 'Create a resume', exact: true })
  await expect(chooser).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('create-resume-desktop.png') })
  await page.keyboard.press('Escape')
  await expect(chooser).toHaveCount(0)
  await expect(create).toBeFocused()
  await create.click()
  await chooser.getByRole('button', { name: /^Create a new resume/ }).click()
  await expect(page).toHaveURL(/\/setup\?new=1$/)
  await expect(page.getByRole('button', { name: /^Preview .* template$/ })).toHaveCount(9)
  await page.getByRole('button', { name: 'Preview Harvard template', exact: true }).click()
  await page.getByRole('button', { name: 'Use this template', exact: true }).click()
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByText('Saved to your account', { exact: true }).first().waitFor()
  await page.getByRole('link', { name: 'Home', exact: true }).click()
    await page.getByRole('navigation', { name:'Workspace', exact:true }).getByRole('link', { name:'Resume', exact:true }).click()
  await expect(page.getByRole('button', { name: 'Delete resume', exact: true })).toBeHidden()
  await page.getByLabel('More options for Resume Creator — Resume', { exact: true }).click()
  await expect(page.getByRole('button', { name: 'Delete resume', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'New resume', exact: true })).toHaveCount(0)
  await expect(page.getByRole('link', { name: 'Import resume', exact: true })).toHaveCount(1)
  await page.screenshot({ path: testInfo.outputPath('resume-workspace-desktop.png'), fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: testInfo.outputPath('resume-workspace-mobile.png'), fullPage: true })
  await create.click()
  await expect(chooser).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('create-resume-mobile.png') })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await chooser.getByRole('button', { name: /^Import existing resume/ }).click()
  await expect(page).toHaveURL(/\/resume\/import$/)
  await expect(page.getByRole('dialog', { name: 'Import Resume', exact: true })).toBeVisible()
  await expect(chooser).toHaveCount(0)
})
