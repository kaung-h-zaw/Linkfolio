import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { hydrateProfile } from '../src/lib/profile.js'
import { defaultPortfolio } from '../src/lib/portfolio.js'
const headers = {'X-Linkfolio-Request':'1'}

test('older copies recover their resume, use saved resume updates, switch sources and lock URL edits', async ({page},testInfo) => {
  const errors = []
  page.on('pageerror',(error) => errors.push(error.message))
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Source Owner',email:`source-${crypto.randomUUID()}@example.com`,password:'source test password'}})
  await page.goto('/premium')
  await page.getByRole('button',{name:'Try demo upgrade',exact:true}).click()
  await page.getByRole('button',{name:'Simulate successful payment',exact:true}).click()
  await page.getByText('Demo payment successful. Premium is active.',{exact:true}).waitFor()
  const firstId = crypto.randomUUID(), secondId = crypto.randomUUID(), portfolioId = crypto.randomUUID()
  const first = {...sampleProfile,id:firstId,kind:'resume',name:'Original resume',templateId:'essential',portfolio:undefined}
  const second = {...first,id:secondId,name:'Other resume',personal:{...first.personal,fullName:'Another Owner',headline:'Researcher'}}
  const copy = {...first,id:portfolioId,kind:'portfolio',name:'Older portfolio',portfolio:{...defaultPortfolio,availability:'Open to work'}}
  for (const document of [first,second,copy]) expect((await page.request.put(`/api/documents/${document.id}`,{headers,data:document})).status()).toBe(200)
  await page.goto(`/portfolio/editor?resume=${portfolioId}`)
  await expect(page.getByLabel('Resume',{exact:true})).toHaveValue(firstId)
  await expect(page.locator('#editor-content')).toContainText('Original resume')
  await expect(page.getByRole('button',{name:'Edit personal details',exact:true})).toHaveCount(0)
  await expect(page.getByRole('button',{name:/Professional Experience/})).toHaveCount(0)
  await expect(page.getByRole('link',{name:'Home',exact:true})).toHaveAttribute('href','/dashboard')
  await page.screenshot({path:testInfo.outputPath('selected-resume-desktop.png')})
  expect((await page.request.put(`/api/documents/${firstId}`,{headers,data:{...first,personal:{...first.personal,headline:'Recovered link update'}}})).status()).toBe(200)
  await page.reload()
  await expect(page.locator('#editor-preview h1')).toHaveText('Recovered link update')
  await page.getByRole('button',{name:'Edit resume',exact:true}).click()
  await expect(page).toHaveURL(new RegExp(`/editor\\?resume=${firstId}`))
  await page.getByRole('button',{name:'Edit personal details',exact:true}).click()
  await page.getByLabel('Professional title',{exact:true}).fill('Updated source headline')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.goto(`/portfolio/editor?resume=${portfolioId}`)
  await expect(page.locator('#editor-preview h1')).toHaveText('Updated source headline')
  await expect(page.getByLabel('Resume',{exact:true})).toHaveValue(firstId)
  await page.getByLabel('Resume',{exact:true}).selectOption(secondId)
  await expect(page.getByLabel('Resume',{exact:true})).toHaveValue(secondId)
  await expect(page.locator('#editor-preview h1')).toHaveText('Researcher')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.getByRole('button',{name:'Sharing',exact:true}).click()
  const url = page.getByLabel('Portfolio URL',{exact:true})
  const originalSlug = await url.inputValue()
  await expect(url).toHaveAttribute('readonly','')
  await page.getByRole('button',{name:'Edit URL',exact:true}).click()
  await url.fill('unsaved-address')
  await page.getByRole('button',{name:'Cancel',exact:true}).click()
  await expect(url).toHaveValue(originalSlug)
  await page.getByRole('button',{name:'Edit URL',exact:true}).click()
  const slug = `source-${portfolioId.slice(0,8)}`
  await url.fill(slug)
  await page.getByRole('button',{name:'Save URL',exact:true}).click()
  await expect(page.getByRole('status').filter({hasText:'Portfolio URL updated.'})).toBeVisible()
  await expect(url).toHaveAttribute('readonly','')
  await page.getByLabel('Visibility',{exact:true}).selectOption('public')
  await page.getByRole('button',{name:'Publish portfolio',exact:true}).click()
  await expect(page.getByText('Your portfolio is published.',{exact:true})).toBeVisible()
  await page.reload()
  await expect(url).toHaveValue(slug)
  // A source edit changes public content while the portfolio address stays fixed.
  const changed = {...second,personal:{...second.personal,headline:'Senior Researcher'}}
  expect((await page.request.put(`/api/documents/${secondId}`,{headers,data:changed})).status()).toBe(200)
  const published = await (await page.request.get(`/api/public/portfolios/${slug}`)).json()
  expect(published.profile.personal.headline).toBe('Senior Researcher')
  expect(published.settings.sourceResume).toBeUndefined()
  await page.reload()
  await expect(url).toHaveValue(slug)
  await expect(page.locator('#editor-preview h1')).toHaveText('Senior Researcher')
  await page.setViewportSize({width:390,height:844})
  await page.getByRole('button',{name:'Content',exact:true}).click()
  await expect(page.getByLabel('Resume',{exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Edit resume',exact:true})).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('selected-resume-mobile.png')})
  expect(errors).toEqual([])
})

test('switching an older attached portfolio keeps both source resumes and its URL intact', async ({page}) => {
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Attached Owner',email:`attached-${crypto.randomUUID()}@example.com`,password:'attached test password'}})
  await page.goto('/premium')
  await page.getByRole('button',{name:'Try demo upgrade',exact:true}).click()
  await page.getByRole('button',{name:'Simulate successful payment',exact:true}).click()
  await page.getByText('Demo payment successful. Premium is active.',{exact:true}).waitFor()
  const originalId = crypto.randomUUID(), otherId = crypto.randomUUID()
  const original = {...sampleProfile,id:originalId,kind:'resume',name:'Original',templateId:'essential',portfolio:defaultPortfolio}
  const other = {...sampleProfile,id:otherId,kind:'resume',name:'Other',templateId:'classic',personal:{...sampleProfile.personal,fullName:'Other person',headline:'Writer'}}
  for (const document of [original,other]) expect((await page.request.put(`/api/documents/${document.id}`,{headers,data:document})).status()).toBe(200)
  let documents = (await (await page.request.get('/api/documents')).json()).documents
  const initial = documents.find((item) => item.id === originalId)
  await page.goto(`/portfolio/editor?resume=${originalId}`)
  await page.getByLabel('Resume',{exact:true}).selectOption(otherId)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(page.locator('#editor-preview h1')).toHaveText('Writer')
  documents = (await (await page.request.get('/api/documents')).json()).documents
  const saved = documents.find((item) => item.id === originalId)
  expect(saved.personal).toEqual(hydrateProfile(initial).personal)
  expect(saved.templateId).toBe(initial.templateId)
  expect(saved.publication.slug).toBe(initial.publication.slug)
  expect(saved.portfolio.sourceResume.id).toBe(otherId)
  expect(documents.find((item) => item.id === otherId).personal).toEqual(other.personal)
})
