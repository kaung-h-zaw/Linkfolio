import { openGeneralGroup } from './helpers/designControls.js'
import { setControlValue } from './helpers/designControls.js'
import { test, expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
const headers = { 'X-Linkfolio-Request':'1' }

test('text and spacing sliders support exact values, limits, undo, reset and saving', async ({ page }, testInfo) => {
  await page.request.post('/api/auth/register', { headers, data:{ fullName:'Spacing owner', email:`spacing-${crypto.randomUUID()}@example.com`, password:'spacing password' } })
  const id = crypto.randomUUID()
  expect((await page.request.put(`/api/documents/${id}`, { headers, data:{ ...sampleProfile,id,kind:'resume',name:'Text and spacing',templateId:'essential' } })).status()).toBe(200)
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('navigation', {name:'Editor navigation',exact:true}).getByRole('button', {name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Text sizes')
  const text = page.getByRole('region', {name:'Text size',exact:true})
  const spacing = page.getByRole('region', {name:'Spacing',exact:true})
  const paper = page.locator('#editor-preview .resume-page').first()
  await expect(text.getByRole('slider')).toHaveCount(5)
  await expect(text.getByRole('spinbutton')).toHaveCount(0)
  await expect(text.locator('output').first()).toHaveText('10.5 pt')
  await text.getByRole('button', {name:'Increase Name size',exact:true}).click()
  await expect(text.getByRole('slider', {name:'Name size',exact:true})).toHaveValue('29')
  await page.getByRole('button', {name:'Undo styling',exact:true}).click()
  await expect(text.getByRole('slider', {name:'Name size',exact:true})).toHaveValue('28')
  const body = text.getByRole('slider', {name:'Body size',exact:true})
  await body.focus()
  await page.keyboard.press('End')
  await expect(text.getByRole('slider', {name:'Body size',exact:true})).toHaveValue('18')
  await expect(text.getByRole('button', {name:'Increase Body size',exact:true})).toBeDisabled()
  await page.keyboard.press('Home')
  await expect(text.getByRole('button', {name:'Decrease Body size',exact:true})).toBeDisabled()
  const track = await body.boundingBox()
  await body.click({position:{x:track.width * 0.65,y:track.height / 2}})
  await expect(body).toHaveValue('16')
  await page.keyboard.press('ArrowRight')
  await expect(body).toHaveValue('17')
  await setControlValue(text.getByRole('slider', {name:'Body size',exact:true}), '16')
  await expect(body).toHaveValue('16')
  await expect(paper).toHaveCSS('--design-size','16px')
  await text.getByRole('button', {name:'Use suggested text sizes',exact:true}).click()
  await expect(body).toHaveValue('14')
  await expect(text.getByRole('button', {name:'Use suggested text sizes',exact:true})).toHaveAttribute('aria-pressed','true')
  await setControlValue(text.getByRole('slider', {name:'Body size',exact:true}), '15')
  await text.getByRole('button', {name:'Reset font size',exact:true}).click()
  await expect(body).toHaveValue('14')
  const name = text.getByRole('slider', {name:'Name size',exact:true})
  await setControlValue(name,'40')
  await text.getByRole('button', {name:'Increase full name by 9 points',exact:true}).click()
  await expect(name).toHaveValue('52')
  await expect(paper.locator('header h2')).toHaveCSS('font-size','52px')
  await page.screenshot({path:testInfo.outputPath('larger-name-desktop.png')})
  await page.getByRole('button', {name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await page.getByRole('navigation', {name:'Editor navigation',exact:true}).getByRole('button', {name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Text sizes')
  await expect(name).toHaveValue('52')
  await expect(text.getByRole('spinbutton')).toHaveCount(0)
  await text.getByRole('button', {name:'Reset font size',exact:true}).click()
  await openGeneralGroup(page,'Spacing')
  await expect(spacing.getByRole('slider')).toHaveCount(5)
  await spacing.getByRole('button', {name:'Balanced spacing',exact:true}).click()
  const line = spacing.getByRole('slider', {name:'Line height',exact:true})
  await expect(line).toHaveValue('1.45')
  await spacing.getByRole('button', {name:'Increase Line height',exact:true}).click()
  await expect(line).toHaveValue('1.5')
  await spacing.getByRole('button', {name:'Use suggested spacing',exact:true}).click()
  await expect(line).toHaveValue('1.45')
  await spacing.getByRole('button', {name:'Increase Line height',exact:true}).click()
  await setControlValue(spacing.getByRole('slider', {name:'Left & right margins',exact:true}), '50')
  await expect(paper).toHaveCSS('padding-left','50px')
  await page.getByRole('button', {name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await page.getByRole('navigation', {name:'Editor navigation',exact:true}).getByRole('button', {name:'Design',exact:true}).click()
  await expect(line).toHaveValue('1.5')
  await expect(spacing.getByRole('slider', {name:'Left & right margins',exact:true})).toHaveValue('50')
  for (const width of [1440,768,390,320]) {
    await page.setViewportSize({width,height:1000})
    await openGeneralGroup(page,'Text sizes')
    await expect.poll(async () => Math.abs((await text.boundingBox()).y - (await page.locator('#editor-content').boundingBox()).y - 16)).toBeLessThan(3)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const card of [text,spacing]) expect(await card.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true)
    await page.screenshot({path:testInfo.outputPath(`text-size-${width}.png`)})
    await openGeneralGroup(page,'Spacing')
    await expect.poll(async () => Math.abs((await spacing.boundingBox()).y - (await page.locator('#editor-content').boundingBox()).y - 16)).toBeLessThan(3)
    await page.screenshot({path:testInfo.outputPath(`spacing-${width}.png`)})
  }
  await spacing.getByRole('button', {name:'Reset spacing',exact:true}).click()
  await expect(line).toHaveValue('1.35')
})
