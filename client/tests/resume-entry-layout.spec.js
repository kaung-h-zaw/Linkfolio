import { openGeneralGroup } from './helpers/designControls.js'
import { test, expect } from '@playwright/test'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { getDesign } from '../src/lib/resumeDesign.js'
import { getProjects } from '../src/lib/additionalSections.js'
const headers = { 'X-Linkfolio-Request':'1' }

test('entry controls apply across sections and show date/location order without Advanced', async ({ page }, testInfo) => {
  await page.request.post('/api/auth/register', {headers,data:{fullName:'Entry owner',email:`entry-order-${crypto.randomUUID()}@example.com`,password:'entry layout password'}})
  const id=crypto.randomUUID()
  const projects=getProjects(structuredClone(sampleProfile))
  projects.entries[0].startDate='2024-01'
  projects.entries[0].endDate='2024-06'
  expect((await page.request.put(`/api/documents/${id}`, {headers,data:{...sampleProfile,id,kind:'resume',name:'Entry layout',templateId:'essential',projectsSection:projects,design:getDesign({entryLayout:'columns',sectionStyles:{experience:{entryLayout:'full',title:'Work history'},education:{entryLayout:'columns'}}})}})).status()).toBe(200)
  await page.setViewportSize({width:1440,height:1000})
  await page.goto(`/editor?resume=${id}`)
  const nav=page.getByRole('navigation',{name:'Design settings',exact:true})
  const editorNav=page.getByRole('navigation',{name:'Editor navigation',exact:true})
  await editorNav.getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Entries')
  const card=page.getByRole('region',{name:'Entry layout',exact:true})
  await expect(card.locator('details,summary')).toHaveCount(0)
  await card.getByRole('button',{name:'Date & location position: Right',exact:true}).click()
  await expect(page.locator('#editor-preview .resume-page [data-section=experience]').first()).not.toHaveAttribute('data-section-entry-layout')
  await expect(page.locator('#editor-preview .resume-page [data-section=experience] h3').first()).toHaveText('Work history')
  const meta=page.locator('#editor-preview .resume-page [data-section=experience] .resume-entry-meta').first()
  await expect(meta.locator('p').first()).toHaveClass(/resume-entry-dates/)
  await card.getByRole('button',{name:'Date & location order: Location – Date',exact:true}).click()
  await expect(meta.locator('p').first()).toHaveClass(/resume-entry-location/)
  await expect(meta.locator('p').last()).toHaveClass(/resume-entry-dates/)
  await card.getByRole('button',{name:'Entry structure: Full width',exact:true}).click()
  await expect(meta).toHaveCSS('display','flex')
  await expect(meta.locator('p').first()).toHaveClass(/resume-entry-location/)
  await card.getByRole('button',{name:'Entry structure: Columns',exact:true}).click()
  await card.getByRole('button',{name:'Date & location position: Left',exact:true}).click()
  await expect(meta).toHaveCSS('grid-column-start','1')
  const entry=page.locator('#editor-preview .resume-page [data-section=experience] .resume-entry').first()
  const title=entry.locator('h4').first(), body=entry.locator('.resume-entry-main > .mt-2')
  expect(Math.abs((await title.boundingBox()).x-(await body.boundingBox()).x)).toBeLessThan(1)
  expect((await meta.boundingBox()).x+(await meta.boundingBox()).width).toBeLessThan((await body.boundingBox()).x)
  await page.screenshot({path:testInfo.outputPath('entries-left.png')})
  const projectMeta=page.locator('#editor-preview .resume-page [data-section=projects] .resume-entry-meta').first()
  await expect(projectMeta).toBeVisible()
  await expect(projectMeta).toHaveCSS('grid-column-start','1')
  await card.getByRole('button',{name:'Date & location position: Split',exact:true}).click()
  await card.getByRole('button',{name:'Date & location order: Date – Location',exact:true}).click()
  const dates=entry.locator('.resume-entry-dates'), location=entry.locator('.resume-entry-location')
  const main=await entry.locator('.resume-entry-main').boundingBox()
  expect((await dates.boundingBox()).x).toBeLessThan(main.x)
  expect((await location.boundingBox()).x).toBeGreaterThan(main.x+main.width)
  expect(Math.abs((await title.boundingBox()).x-(await body.boundingBox()).x)).toBeLessThan(1)
  const secondMain=page.locator('#editor-preview .resume-page [data-section=experience] .resume-entry-main').nth(1)
  expect(Math.abs((await secondMain.boundingBox()).x-main.x)).toBeLessThan(1)
  await page.screenshot({path:testInfo.outputPath('entries-split.png')})
  const pageCount=await page.locator('#editor-preview .resume-page').count()
  const downloadEvent=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download resume',exact:true}).click()
  const download=await downloadEvent
  const pdfPath=testInfo.outputPath('split-entries.pdf')
  await download.saveAs(pdfPath)
  const {getDocument,OPS}=await import('pdfjs-dist/legacy/build/pdf.mjs')
  const {readFile}=await import('node:fs/promises')
  const loading=getDocument({data:new Uint8Array(await readFile(pdfPath)),useSystemFonts:true})
  const pdf=await loading.promise
  expect(pdf.numPages).toBe(pageCount)
  for(let index=1;index<=pdf.numPages;index++) {
    const operators=await (await pdf.getPage(index)).getOperatorList()
    expect(operators.fnArray.some((operator)=>[OPS.paintImageXObject,OPS.paintInlineImageXObject].includes(operator))).toBe(true)
  }
  await loading.destroy()
  await card.getByRole('button',{name:'Date & location order: Location – Date',exact:true}).click()
  expect((await dates.boundingBox()).x).toBeGreaterThan(main.x+main.width)
  await card.getByRole('button',{name:'Date & location position: Right',exact:true}).click()
  await expect(meta).toHaveCSS('text-align','right')
  await card.getByRole('button',{name:'Subtitle placement: Same line',exact:true}).click()
  await expect(page.locator('#editor-preview .resume-page [data-section=certifications] .resume-entry-subtitle').first()).toHaveCSS('display','inline')
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await editorNav.getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page,'Entries')
  await expect(card.getByRole('button',{name:'Date & location order: Location – Date',exact:true})).toHaveAttribute('aria-pressed','true')
  await expect(meta.locator('p').first()).toHaveClass(/resume-entry-location/)
  for(const width of [1440,390,320]) {
    await page.setViewportSize({width,height:1000})
    await openGeneralGroup(page,'Entries')
    await expect.poll(async()=>Math.abs((await card.boundingBox()).y-(await page.locator('#editor-content').boundingBox()).y-16)).toBeLessThan(3)
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
    await page.screenshot({path:testInfo.outputPath(`entry-layout-${width}.png`)})
  }
  await card.getByRole('button',{name:'Reset entry layout',exact:true}).click()
  await expect(card.getByRole('button',{name:'Date & location order: Date – Location',exact:true})).toHaveAttribute('aria-pressed','true')
})
