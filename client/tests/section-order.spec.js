import { openGeneralGroup } from './helpers/designControls.js'
import { test, expect } from '@playwright/test'
import { sampleProfile } from '../src/components/resumeTemplates.js'
const headers = { 'X-Linkfolio-Request': '1' }

test('section drag handles reorder the preview and retain the saved order', async ({ page }, testInfo) => {
  await page.request.post('/api/auth/register', { headers, data: { fullName: 'Section owner', email: `order-${crypto.randomUUID()}@example.com`, password: 'section password' } })
  const id = crypto.randomUUID()
  await page.request.put(`/api/documents/${id}`, { headers, data: { ...sampleProfile, id, kind: 'resume', name: 'Section order', templateId: 'essential' } })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`/editor?resume=${id}`)
  async function openOrder() {
    await page.getByRole('navigation', { name: 'Editor navigation', exact: true }).getByRole('button', { name: 'Design', exact: true }).click()
    await openGeneralGroup(page,'Layout')
  }
  await openOrder()
  const rows = page.locator('.resume-arrange-row')
  const original = await rows.evaluateAll((elements) => elements.map((element) => element.dataset.orderSection))
  expect(original.length).toBeGreaterThan(2)
  await rows.first().scrollIntoViewIfNeeded()
  const handle = rows.first().getByRole('button', { name: /Drag .* to reorder/ })
  const start = await handle.boundingBox()
  const startingRow = await rows.first().boundingBox()
  const end = await rows.nth(1).boundingBox()
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(end.x + 80, end.y + end.height / 2, { steps: 10 })
  await expect(rows.first()).toHaveAttribute('data-order-section', original[1])
  await expect(page.locator('.section-drag-floating')).toBeVisible()
  const floating = await page.locator('.section-drag-floating').boundingBox()
  expect(Math.abs(floating.y - (end.y + end.height / 2 - (start.y + start.height / 2 - startingRow.y)))).toBeLessThan(2)
  await page.screenshot({ path: testInfo.outputPath('section-drag-in-progress.png') })
  await page.mouse.up()
  await expect(rows.first()).toHaveAttribute('data-order-section', original[1])
  await expect(rows.nth(1)).toHaveAttribute('data-order-section', original[0])
  await expect.poll(() => page.locator('#editor-preview .resume-page [data-section]').evaluateAll((elements) => [...new Set(elements.map((element) => element.dataset.section))].slice(0, 2))).toEqual([original[1], original[0]])
  await expect(page.getByRole('button', { name: /^Move .* (up|down)$/ })).toHaveCount(0)
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await openOrder()
  await expect(rows.first()).toHaveAttribute('data-order-section', original[1])
  await rows.first().getByRole('button', { name: /Drag .* to reorder/ }).focus()
  await page.keyboard.press('ArrowDown')
  await expect(rows.first()).toHaveAttribute('data-order-section', original[0])
  await page.getByRole('button', { name: 'Add page break', exact: true }).click()
  await expect(rows.last()).toHaveAttribute('data-order-section', /^break:/)
  const removeBreak = rows.last().getByRole('button', { name: 'Remove page break', exact: true })
  await expect(removeBreak.locator('svg')).toHaveCount(1)
  expect(await removeBreak.textContent()).toBe('')
  await removeBreak.click()
  await expect(rows).toHaveCount(original.length)
  // The body of the box is draggable too, away from the grip button.
  await rows.first().scrollIntoViewIfNeeded()
  const boxStart = await rows.first().boundingBox()
  const boxEnd = await rows.nth(1).boundingBox()
  await page.mouse.move(boxStart.x + boxStart.width - 60, boxStart.y + boxStart.height / 2)
  await page.mouse.down()
  await page.mouse.move(boxEnd.x + boxEnd.width - 60, boxEnd.y + boxEnd.height / 2, { steps: 10 })
  await page.mouse.up()
  await expect(rows.first()).toHaveAttribute('data-order-section', original[1])
  await page.screenshot({ path: testInfo.outputPath('section-order-cards.png') })
  await rows.first().scrollIntoViewIfNeeded()
  const cancelStart=await rows.first().boundingBox(),cancelEnd=await rows.nth(1).boundingBox()
  await page.mouse.move(cancelStart.x + 100, cancelStart.y + cancelStart.height / 2)
  await page.mouse.down()
  await page.mouse.move(cancelEnd.x + 100, cancelEnd.y + cancelEnd.height / 2, { steps: 10 })
  await expect(rows.first()).toHaveAttribute('data-order-section', original[0])
  await page.keyboard.press('Escape')
  await expect(page.locator('.section-drag-floating')).toHaveCount(0)
  await expect(rows.first()).toHaveAttribute('data-order-section', original[1])
  await page.mouse.up()
  await page.getByRole('button', { name: 'Reset section order', exact: true }).click()
  expect(await rows.evaluateAll((elements) => elements.map((element) => element.dataset.orderSection))).toEqual(original)
})
