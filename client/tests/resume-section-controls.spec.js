import { openSectionCard } from './helpers/designControls.js'
import { test,expect } from './fixtures.js'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { textDocument } from '../src/lib/summary.js'
import { getSkills } from '../src/lib/educationSkills.js'
import { newLanguage } from '../src/lib/additionalSections.js'
const headers={'X-Linkfolio-Request':'1'}
test('collapsible customization groups expose real summary, title and collection controls',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.request.post('/api/auth/register',{headers,data:{fullName:'Section options owner',email:`section-options-${crypto.randomUUID()}@example.com`,password:'section options password'}})
  const id=crypto.randomUUID(),skills=getSkills(structuredClone(sampleProfile));skills.entries[0].level='Expert'
  const summary=textDocument('A clear introduction to my work.')
  const profile={...sampleProfile,id,kind:'resume',name:'Section controls',templateId:'essential',summarySection:{heading:'Summary',entries:[{id:'summary',visible:true,content:summary}]},skillsSection:skills,languagesSection:{heading:'Languages',entries:[{...newLanguage(),name:'English',level:'Fluent'},{...newLanguage(),name:'Burmese',level:'Native/Bilingual'}]}}
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:profile})).status()).toBe(200)
  await page.goto(`/editor?resume=${id}`)
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  const group=page.getByRole('button',{name:'Section customizations',exact:true}),general=page.getByRole('button',{name:'General',exact:true})
  await expect(page.getByRole('tablist',{name:'Customization'})).toHaveCount(0)
  await expect(general).toHaveAttribute('aria-expanded','true')
  await group.click()
  await expect(general).toHaveAttribute('aria-expanded','false')
  await expect(page.getByRole('navigation',{name:'Design settings',exact:true})).toHaveCount(0)
  await expect(page.locator('[data-section-choice]')).toHaveCount(0)
  await expect(page.getByLabel('Show on resume',{exact:true})).toHaveCount(0)
  await expect(page.getByLabel('Section heading',{exact:true})).toHaveCount(0)
  await expect(page.getByText('Arrange sections',{exact:true})).toHaveCount(0)
  await expect(page.locator('[data-section-customization]')).toHaveCount(6)
  const choose=key=>openSectionCard(page,key)
  const pages=page.locator('#editor-preview .resume-page')
  await expect(page.locator('[data-section-customization=summary]')).toHaveCount(0)
  await choose('experience')
  await expect(page.getByText('Group promotions',{exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Title order: Employer – Job title',exact:true}).click()
  await expect(pages.locator('[data-section=experience] h4').first()).toHaveText('North Studio')
  await expect(pages.locator('[data-section=experience] .resume-entry-subtitle').first()).toHaveText('Senior Product Designer')
  await page.screenshot({path:testInfo.outputPath('work-customization.png')})
  await choose('education')
  await page.getByRole('button',{name:'Title order: School – Degree',exact:true}).click()
  await expect(pages.locator('[data-section=education] h4').first()).toHaveText('Pacific Design College')
  await choose('skills')
  await page.getByRole('button',{name:'Skills style: Grid',exact:true}).click()
  await page.getByRole('button',{name:'Skills columns: 3',exact:true}).click()
  const skillGrid=pages.locator('[data-section=skills] .resume-skills').first()
  expect((await skillGrid.evaluate(node=>getComputedStyle(node).gridTemplateColumns.split(' '))).length).toBe(3)
  await expect(pages.locator('[data-section=skills] .resume-skill h4')).toHaveCount(6)
  await expect(page.getByRole('button',{name:'Skills style: Level',exact:true})).toHaveCount(0)
  await choose('languages')
  await page.getByRole('button',{name:'Languages style: Bubble',exact:true}).click()
  await expect(pages.locator('[data-section=languages] .resume-section-collection')).toHaveCSS('display','flex')
  await expect(page.getByRole('button',{name:'Languages style: Level',exact:true})).toHaveCount(0)
  await choose('certifications')
  await expect(page.getByRole('button',{name:'Certifications style: Level',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Certifications style: Grid',exact:true}).click()
  await page.getByRole('button',{name:'Certifications columns: 2',exact:true}).click()
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(pages.locator('[data-section=summary]')).toHaveCount(1)
  await expect(pages.locator('[data-section=experience] h4').first()).toHaveText('North Studio')
  await expect(pages.locator('[data-section=languages]')).toContainText('Fluent')
  const saved=(await (await page.request.get('/api/documents')).json()).documents.find(item=>item.id===id)
  expect(saved.summarySection.entries[0].content).toEqual(summary)
  const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'Download resume',exact:true}).click();const download=await downloadEvent;await download.saveAs(testInfo.outputPath('section-controls.pdf'));expect(await download.failure()).toBeNull()
  await page.getByRole('navigation',{name:'Editor navigation',exact:true}).getByRole('button',{name:'Design',exact:true}).click()
  await group.click();await choose('skills')
  await page.setViewportSize({width:320,height:900})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  await page.locator('[data-section-customization=skills]').screenshot({path:testInfo.outputPath('skills-controls-mobile.png')})
  await group.click();await expect(group).toHaveAttribute('aria-expanded','false')
  await general.click();await expect(general).toHaveAttribute('aria-expanded','true')
  expect(errors).toEqual([])
})
