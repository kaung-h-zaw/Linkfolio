import { openGeneralGroup, openSectionCard } from './helpers/designControls.js'
import { test, expect } from './fixtures.js'
import { fileURLToPath } from 'node:url'
import { sampleProfile } from '../src/components/resumeTemplates.js'
import { defaultPortfolio } from '../src/lib/portfolio.js'
import { getProjects } from '../src/lib/additionalSections.js'
import { portraitStylePresets } from '../src/lib/portfolioDesign.js'
import { portfolioDemoImages } from '../src/lib/portfolioImages.js'

const headers = { 'X-Linkfolio-Request':'1' }
const choices = [['bento','Mosaic'],['macfolio','Workbench'],['nocturne','Signal'],['strata','Meridian'],['miniport','Clear'],['press','Folio'],['massively','Panorama'],['multiverse','Aperture'],['freelancer','Summit']]
test('nine sourced portfolio designs, image uploads, persistence and public privacy', async ({ page },testInfo) => {
  const errors = []
  page.on('pageerror',(error) => errors.push(error.message))
  expect((await page.request.post('/api/auth/register',{ headers,data:{ fullName:'Portfolio Tester',email:`portfolio-${crypto.randomUUID()}@example.com`,password:'portfolio test password' } })).status()).toBe(201)
  await page.goto('/premium')
  await page.getByRole('button',{name:'Try demo upgrade',exact:true}).click()
  await page.getByRole('button',{name:'Simulate successful payment',exact:true}).click()
  await page.getByText('Demo payment successful. Premium is active.',{exact:true}).waitFor()
  const projects = getProjects(sampleProfile)
  projects.entries.push({ ...projects.entries[0],id:'public-second',name:'Product Design System' })
  projects.entries.push({ ...projects.entries[0],id:'hidden-project',visible:false,name:'Private prototype' })
  const id = crypto.randomUUID()
  const contactLinks = [
    {id:'site',type:'Website',label:'My website',url:'https://example.com'},
    {id:'linkedin',type:'Custom link',label:'Professional profile',url:'https://www.linkedin.com/in/example'},
    {id:'github',type:'GitHub',label:'My code',url:'https://github.com/example'},
    {id:'youtube',type:'Custom link',label:'Videos',url:'https://youtu.be/example'},
    {id:'custom',type:'Custom link',label:'My research',url:'https://research.example.org'},
    {id:'spoof',type:'Custom link',label:'Other website',url:'https://github.com.example.org'},
  ]
  const document = { ...sampleProfile,personal:{...sampleProfile.personal,links:contactLinks},id,kind:'portfolio',name:'Portfolio Test',templateId:'essential',projectsSection:projects,portfolio:{ ...defaultPortfolio,introduction:'I design clear, accessible digital products.',images:{ portrait:portfolioDemoImages.portrait,cover:portfolioDemoImages.cover,projects:Object.fromEntries(projects.entries.map((entry,index) => [entry.id,portfolioDemoImages.projectCovers[index % 3]])) } } }
  expect((await page.request.put(`/api/documents/${id}`,{headers,data:document})).status()).toBe(200)
  await page.goto(`/portfolio/editor?resume=${id}`)
  await page.getByRole('button',{name:'Sharing',exact:true}).click()
  await expect(page.getByLabel('Portfolio URL',{exact:true})).toHaveValue(/[a-z0-9-]+-\d{6}$/)
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await page.getByText('Choose portfolio template',{exact:true}).click()
  await expect(page.getByRole('button',{name:/^Use .* template$/})).toHaveCount(9)
  await expect(page.getByText(/Inspiration:/)).toHaveCount(0)
  await expect(page.getByRole('link',{name:/Research reference/})).toHaveCount(0)
  for (const [,name] of choices) await expect(page.getByRole('button',{name:`Use ${name} template`,exact:true}).locator('span.block.p-3')).toHaveText(name)
  for (const [template,name] of choices) {
    await page.getByRole('button',{name:`Use ${name} template`,exact:true}).click()
    await expect(page.locator('#editor-preview [data-web-source]')).toHaveAttribute('data-web-source',template)
    await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-design-origin','linkfolio')
    await expect(page.locator('#editor-preview .portfolio-footer')).not.toContainText('Design adapted from')
    await expect(page.locator('#editor-preview .portfolio-project-image')).toHaveCount(2)
    await page.getByRole('button',{name:'Save',exact:true}).click()
    await page.getByText('Saved to your account',{exact:true}).first().waitFor()
    const slug = `design-${template}-${id.slice(0,8)}`
    expect((await page.request.put(`/api/documents/${id}/publication`,{headers,data:{slug,visibility:'public'}})).status()).toBe(200)
    const publicData = await (await page.request.get(`/api/public/portfolios/${slug}`)).json()
    expect(publicData.settings.images.cover).toBeUndefined()
    expect(publicData.settings.images.projects['hidden-project']).toBeUndefined()
    const visitor = await page.context().newPage()
    await visitor.goto(`/p/${slug}`)
    const navigation = visitor.getByRole('navigation',{name:'Portfolio navigation'})
    const sectionLink = navigation.getByRole('link',{name:'Contact',exact:true})
    await expect(sectionLink).toHaveAttribute('href','#contact')
    const socialLinks = visitor.getByRole('navigation',{name:'Contact and social links'})
    await expect(socialLinks.getByRole('link')).toHaveCount(7)
    await expect(socialLinks.getByRole('link',{name:'GitHub: My code',exact:true})).toHaveAttribute('href','https://github.com/example')
    await expect(socialLinks.getByRole('link',{name:'LinkedIn: Professional profile',exact:true})).toHaveAttribute('href','https://www.linkedin.com/in/example')
    await expect(socialLinks.getByRole('link',{name:'YouTube: Videos',exact:true})).toHaveAttribute('href','https://youtu.be/example')
    await expect(socialLinks.getByRole('link',{name:'My research',exact:true})).toHaveAttribute('title','My research')
    await expect(socialLinks.getByRole('link',{name:'Other website',exact:true})).toBeAttached()
    for (const link of await socialLinks.getByRole('link').all()) {
      await expect(link.locator('svg')).toHaveCount(1)
      expect(await link.innerText()).toBe('')
    }
    await sectionLink.click()
    await expect(sectionLink).toHaveAttribute('aria-current','location')
    expect((await navigation.boundingBox()).y).toBeGreaterThanOrEqual(0)
    expect((await navigation.boundingBox()).y).toBeLessThan(5)
    expect((await visitor.locator('#contact').boundingBox()).y).toBeGreaterThan(70)
    await visitor.evaluate(() => window.scrollTo(0,0))
    await expect(visitor.locator('.portfolio-site')).toHaveAttribute('data-web-source',template)
    await expect.poll(() => visitor.locator('.portfolio-project-image').first().evaluate((img) => img.complete && img.naturalWidth > 0)).toBe(true)
    await visitor.screenshot({path:testInfo.outputPath(`${template}-desktop.png`),fullPage:true})
    await visitor.setViewportSize({width:390,height:844})
    expect(await visitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await visitor.screenshot({path:testInfo.outputPath(`${template}-mobile.png`),fullPage:true})
    await socialLinks.getByRole('link').first().focus()
    await expect(socialLinks.getByRole('link').first()).toBeFocused()
    await visitor.close()
  }
  // Shared design choices must survive every template switch and publication.
  await page.getByRole('button',{name:'Use Mosaic template',exact:true}).click()
  await openGeneralGroup(page, 'Text sizes')
  await page.getByLabel('Portfolio font',{exact:true}).selectOption('serif')
  await openGeneralGroup(page, 'Colors')
  await page.getByLabel('Website colors',{exact:true}).selectOption('dark')
  await openSectionCard(page, 'projects')
  await page.getByText('Project cards',{exact:true}).click()
  await page.getByLabel('Project columns',{exact:true}).selectOption('2')
  await openSectionCard(page, 'hero')
  await page.locator('[data-section-customization=hero]').getByText('Image styling',{exact:true}).click()
  for (const label of ['Personal photo shape','Personal photo frame','Personal photo color effect']) await expect(page.getByLabel(label,{exact:true})).toHaveCount(0)
  const photoSize = page.getByRole('combobox',{name:'Personal photo size',exact:true})
  await photoSize.selectOption('160')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveCSS('--portfolio-portraitSize','160px')
  await photoSize.selectOption('custom')
  await page.getByLabel('Custom photo size (px)',{exact:true}).fill('275')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveCSS('--portfolio-portraitSize','275px')
  await photoSize.selectOption('template')
  await expect(page.getByLabel('Custom photo size (px)',{exact:true})).toHaveCount(0)
  for (const name of ['Arch','Capsule','Organic','Diamond','Hexagon']) await expect(page.getByRole('button',{name:`Personal photo design: ${name}`,exact:true})).toHaveCount(0)
  for (const preset of portraitStylePresets) {
    await page.getByRole('button',{name:`Personal photo design: ${preset.name}`,exact:true}).click()
    await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-portrait-shape',preset.shape)
    await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-portrait-frame',preset.frame)
    const photo = page.locator('#editor-preview .portfolio-portrait')
    if (preset.id === 'diamond' || preset.id === 'hexagon') expect(await photo.evaluate((element) => getComputedStyle(element).clipPath)).toContain('polygon(')
    if (['offset','shadow','raised','layered','floating','mat'].includes(preset.id)) expect(await photo.evaluate((element) => getComputedStyle(element).boxShadow)).not.toBe('none')
  }
  await page.getByRole('button',{name:'Personal photo design: Floating',exact:true}).click()
  await expect(page.getByLabel('Cover proportions',{exact:true})).toHaveCount(0)
  await page.getByLabel('Personal photo focal point',{exact:true}).selectOption('top')
  await page.screenshot({path:testInfo.outputPath('image-design-options.png')})
  await openSectionCard(page, 'projects')
  await page.locator('[data-section-customization=projects]').getByText('Image styling',{exact:true}).click()
  await page.getByLabel('Project image frame',{exact:true}).selectOption('outline')
  await page.getByLabel('Project image color effect',{exact:true}).selectOption('grayscale')
  await page.getByLabel('Project image focal point',{exact:true}).selectOption('top')
  await page.getByLabel('Project image proportions',{exact:true}).selectOption('square')
  await expect(page.getByRole('button',{name:/Tinted panel/})).toHaveCount(0)
  await page.locator('[data-section-customization=projects]').getByText('Edit heading',{exact:true}).click()
  await page.getByLabel('Projects heading',{exact:true}).fill('Selected projects')
  await openSectionCard(page, 'hero')
  await page.getByRole('button',{name:'Introduction: Centered',exact:true}).click()
  await openSectionCard(page, 'certifications')
  await page.getByRole('button',{name:'Certifications: Cards',exact:true}).click()
  await page.getByRole('button',{name:'Content',exact:true}).click()
  await page.getByLabel('Show Education section',{exact:true}).uncheck()
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await page.screenshot({path:testInfo.outputPath('unified-design-editor.png')})
  await openSectionCard(page, 'projects')
  await page.getByRole('button',{name:'Content',exact:true}).click()
  const reorderProjects = page.getByRole('button',{name:'Drag Projects to reorder',exact:true})
  await reorderProjects.press('ArrowUp')
  await reorderProjects.press('ArrowDown')
  await reorderProjects.press('ArrowUp')
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await openGeneralGroup(page, 'Templates')
  await page.getByText('Choose portfolio template', {exact:true}).click()
  for (const [template,name] of choices) {
    await page.getByRole('button',{name:`Use ${name} template`,exact:true}).click()
    const site = page.locator('#editor-preview .portfolio-site')
    await expect(site).toHaveAttribute('data-web-source',template)
    await expect(site.locator('[data-section=projects] h2')).toContainText('Selected projects')
    await expect(site.locator('[data-section=education]')).toHaveCount(0)
    await expect(site.locator('.portfolio-hero')).toHaveCSS('display','flex')
    await expect(site.locator('[data-section=certifications] > .space-y-6')).toHaveCSS('display','grid')
    await expect(site).toHaveCSS('background-color','rgb(17, 24, 39)')
    await expect(site.locator('h1')).toHaveCSS('font-family','Georgia, serif')
    await expect(site.locator('.portfolio-portrait')).toHaveCSS('border-radius','18px')
    const image = site.locator('.portfolio-project-image').first()
    await expect(image).toHaveCSS('aspect-ratio','1 / 1')
    await expect(image).toHaveCSS('filter','grayscale(1)')
    await expect(image).toHaveCSS('border-top-style','solid')
    expect(await image.evaluate((element) => parseFloat(getComputedStyle(element).borderTopWidth))).toBeGreaterThan(0)
    await expect(image).toHaveCSS('object-position','50% 0%')
    await expect(site.locator('.portfolio-hero-image')).toHaveCount(0)
    expect(await site.locator('.portfolio-section[data-section]').first().getAttribute('data-section')).toBe('projects')
    await openSectionCard(page, 'projects')
    await page.getByText('Project cards',{exact:true}).click()
    await expect(page.getByLabel('Project columns',{exact:true})).toHaveValue('2')
    await openGeneralGroup(page, 'Templates')
    await page.getByText('Choose portfolio template', {exact:true}).click()
  }
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-custom-font','true')
  const sharedPublished = await (await page.request.get(`/api/public/portfolios/design-freelancer-${id.slice(0,8)}`)).json()
  expect(sharedPublished.settings.design).toMatchObject({font:'serif',palette:'dark',projectColumns:'2',portraitShape:'rounded',portraitFrame:'floating',imageRatio:'square',imageFrame:'outline',imageEffect:'grayscale',imagePosition:'top'})
  const sharedVisitor = await page.context().newPage()
  await sharedVisitor.goto(`/p/design-freelancer-${id.slice(0,8)}`)
  await expect(sharedVisitor.locator('.portfolio-site h1')).toHaveCSS('font-family','Georgia, serif')
  await sharedVisitor.setViewportSize({width:390,height:844})
  expect(await sharedVisitor.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await sharedVisitor.screenshot({path:testInfo.outputPath('shared-design-mobile.png'),fullPage:true})
  await sharedVisitor.close()
  await page.getByRole('button',{name:'Design',exact:true}).click()
  await page.getByRole('button',{name:'Reset design to template defaults',exact:true}).click()
  await expect(page.locator('#editor-preview .portfolio-site')).not.toHaveAttribute('data-custom-font','true')
  await expect(page.locator('#editor-preview .portfolio-site')).toHaveAttribute('data-web-source','freelancer')
  await expect(page.locator('#editor-preview .portfolio-project-image')).toHaveCount(2)
  await page.getByRole('button',{name:'Content',exact:true}).click()
  await page.getByRole('button',{name:'Change portrait image',exact:true}).click()
  await page.getByLabel('Choose portrait image',{exact:true}).setInputFiles(fileURLToPath(new URL('../public/images/resume-demo.jpg',import.meta.url)))
  await page.getByRole('button',{name:'Use image',exact:true}).click()
  await expect(page.getByAltText('Portrait image preview')).toHaveAttribute('src',/^data:image\/jpeg;base64,/)
  const projectName = projects.entries[0].name
  await page.getByRole('button',{name:`Change project image: ${projectName.toLowerCase()}`,exact:true}).click()
  await page.getByLabel(`Choose project image: ${projectName.toLowerCase()}`,{exact:true}).setInputFiles(fileURLToPath(new URL('../public/images/portfolio-analytics.jpg',import.meta.url)))
  await page.getByRole('button',{name:'Use image',exact:true}).click()
  await expect(page.getByAltText(`Project image: ${projectName} preview`)).toHaveAttribute('src',/^data:image\/jpeg;base64,/)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(page.getByAltText('Portrait image preview')).toHaveAttribute('src',/^data:image\/jpeg;base64,/)
  const published = await (await page.request.get(`/api/public/portfolios/design-freelancer-${id.slice(0,8)}`)).json()
  expect(published.settings.images.portrait).toMatch(/^data:image\/jpeg;base64,/)
  expect(published.settings.images.projects[projects.entries[0].id]).toMatch(/^data:image\/jpeg;base64,/)
  await page.getByLabel('Use resume photo',{exact:true}).check()
  await expect(page.getByAltText('Active personal photo')).toHaveAttribute('src','/images/resume-demo.jpg')
  await expect(page.locator('#editor-preview .portfolio-portrait')).toHaveAttribute('src','/images/resume-demo.jpg')
  await page.getByLabel('Show personal photo',{exact:true}).uncheck()
  await expect(page.locator('#editor-preview .portfolio-portrait')).toHaveCount(0)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(page.getByLabel('Show personal photo',{exact:true})).not.toBeChecked()
  await expect(page.getByAltText('Portrait image preview')).toHaveCount(0)
  await expect(page.getByAltText('Active personal photo')).toHaveCount(0)
  await expect(page.getByLabel('Use custom photo',{exact:true})).toHaveCount(0)
  const hiddenPhoto = await (await page.request.get(`/api/public/portfolios/design-freelancer-${id.slice(0,8)}`)).json()
  expect(hiddenPhoto.settings.images.portrait).toBe('')
  expect(hiddenPhoto.profile.personal.photo).toBeUndefined()
  await page.getByLabel('Show personal photo',{exact:true}).check()
  await page.getByLabel('Use custom photo',{exact:true}).check()
  await expect(page.locator('#editor-preview .portfolio-portrait')).toHaveAttribute('src',/^data:image\/jpeg;base64,/)
  await expect(page.getByAltText('Cover image preview')).toHaveCount(0)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(page.getByAltText('Cover image preview')).toHaveCount(0)
  await page.getByRole('button',{name:'Remove portrait image',exact:true}).click()
  await expect(page.locator('#editor-preview .portfolio-portrait')).toHaveCount(0)
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await page.getByText('Saved to your account',{exact:true}).first().waitFor()
  await page.reload()
  await expect(page.getByLabel('Use custom photo',{exact:true})).toBeChecked()
  await expect(page.locator('#editor-preview .portfolio-portrait')).toHaveCount(0)
  await page.getByLabel('Use resume photo',{exact:true}).check()
  await expect(page.locator('#editor-preview .portfolio-portrait')).toHaveAttribute('src','/images/resume-demo.jpg')
  expect(errors).toEqual([])
})
