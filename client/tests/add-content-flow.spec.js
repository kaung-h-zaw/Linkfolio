import {test,expect} from '@playwright/test'
const headers={'X-Linkfolio-Request':'1'}
test('new resumes add chosen sections and continue directly into entry details',async({page},testInfo)=>{
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.request.post('/api/auth/register',{headers,data:{fullName:'New resume owner',email:`add-flow-${crypto.randomUUID()}@example.com`,password:'adding content password'}})
  await page.goto('/editor?template=classic')
  for(const name of ['Summary','Professional Experience','Education','Skills','Projects','Certifications','Languages'])await expect(page.getByRole('button',{name,exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Add Content',exact:true}).click()
  let dialog=page.getByRole('dialog')
  for(const name of ['Professional Summary','Professional Experience','Education','Skills','Projects','Certifications','Languages'])await expect(dialog.getByRole('button',{name:`Add ${name}`,exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'Add Skills',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Edit skill entry',exact:true})).toBeVisible()
  await expect(dialog).toHaveCount(0)
  await page.getByLabel('Skill',{exact:true}).fill('Web development')
  await page.getByRole('textbox',{name:'Information / Sub-skills',exact:true}).fill('React and accessible interfaces')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByRole('button',{name:'Skills',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Education',exact:true})).toHaveCount(0)
  await page.getByRole('button',{name:'Add Content',exact:true}).click()
  dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('button',{name:'Add Skills',exact:true})).toHaveCount(0)
  await dialog.getByRole('button',{name:'Add Custom section',exact:true}).click()
  await dialog.getByLabel('Section name',{exact:true}).fill('Awards')
  await dialog.getByRole('button',{name:'Custom section type: Standard entries',exact:true}).click()
  await dialog.screenshot({path:testInfo.outputPath('custom-section-setup.png')})
  await dialog.getByRole('button',{name:'Continue',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Edit custom entry',exact:true})).toBeVisible()
  await expect(page.getByLabel('Section name',{exact:true})).toBeHidden()
  await page.getByLabel('Title',{exact:true}).fill('Community award')
  await page.getByRole('textbox',{name:'Description',exact:true}).fill('Recognised for volunteering.')
  await page.getByRole('button',{name:'Done',exact:true}).click()
  await expect(page.getByRole('button',{name:'Awards',exact:true})).toBeVisible()
  await expect(page.getByLabel('Section name',{exact:true})).toHaveCount(0)
  await expect(page.getByText('Content type',{exact:true})).toHaveCount(0)
  await expect(page.locator('#editor-preview .resume-page [data-section=custom]')).toContainText('Community award')
  await page.screenshot({path:testInfo.outputPath('only-chosen-sections.png')})
  await page.getByRole('button',{name:'Save',exact:true}).click()
  await expect(page.locator('.editor-navigation-bar').getByRole('status')).toContainText('Saved to your account')
  await page.reload()
  await expect(page.getByRole('button',{name:'Skills',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Awards',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Professional Experience',exact:true})).toHaveCount(0)
  await page.setViewportSize({width:320,height:900})
  await page.getByRole('button',{name:'Add Content',exact:true}).click()
  await page.getByRole('dialog').getByRole('button',{name:'Add Languages',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Edit language entry',exact:true})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
})
